import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { intentSchema, type Intent } from "./intent.js";
import { pazeClient1Schema, type PazeClient1 } from "./paze-client1.js";
import {
  acceptedpaymentcardnetworksSchema,
  type Acceptedpaymentcardnetworks,
} from "./unions/acceptedpaymentcardnetworks.js";
import {
  acceptedshippingcountriesSchema,
  type Acceptedshippingcountries,
} from "./unions/acceptedshippingcountries.js";
import { billingpreference2Schema, type Billingpreference2 } from "./unions/billingpreference2.js";
import { cobrandSchema, type Cobrand } from "./unions/cobrand.js";
import { emailaddressModelSchema, type EmailaddressModel } from "./unions/emailaddress-model.js";
import { phonenumberModelSchema, type PhonenumberModel } from "./unions/phonenumber-model.js";
import { shippingpreference1Schema, type Shippingpreference1 } from "./unions/shippingpreference1.js";
import { transactionValueSchema, type TransactionValue } from "./unions/transaction-value.js";
import { transactiontype2Schema, type Transactiontype2 } from "./unions/transactiontype2.js";

export type PazeMobileSessionCreateRequest = {
  /** The merchant client integrating with Paze. */
  client: PazeClient1;
  /**
   * Session reference identifier generated by the merchant. Must be reused across all Paze APIs in
   * a checkout session.
   */
  sessionId: string;
  /** Access token obtained from the Paze session endpoint with source=mobile. */
  accessToken: string;
  /**
   * Merchant app's ID (iOS bundle identifier or Android application ID) used as the callback URL
   * scheme.
   */
  callbackUrlScheme: string;
  /** Primary intent of the checkout session. */
  intent: Intent;
  /** Currency and amount of the transaction. Required when intent is EXPRESS_CHECKOUT. */
  transactionValue?: TransactionValue;
  /** Type of transaction. */
  transactionType?: Transactiontype2;
  /** Whether to collect a shipping address from the consumer. */
  shippingPreference?: Shippingpreference1;
  /** Verbosity of billing address required. */
  billingPreference?: Billingpreference2;
  /** Consumer email address for checkout flow optimization. */
  emailAddress?: EmailaddressModel;
  /** Consumer phone number for checkout flow optimization. */
  phoneNumber?: PhonenumberModel;
  /** Details for cobranded cards offered by the merchant. */
  cobrand?: Cobrand;
  /**
   * ISO 3166-1 alpha-2 country codes restricting eligible shipping addresses. Empty list or absence
   * means all countries accepted.
   */
  acceptedShippingCountries?: Acceptedshippingcountries;
  /** Accepted payment card networks. Empty list or absence means all networks accepted. */
  acceptedPaymentCardNetworks?: Acceptedpaymentcardnetworks;
  /**
   * Set to true to enable Paze checkout even if the provided email address or phone number does not
   * match a Paze wallet.
   *
   * @default false
   */
  alwaysEnableCheckout?: boolean;
};

export const pazeMobileSessionCreateRequestSchema: Schema<PazeMobileSessionCreateRequest> =
  s.object<PazeMobileSessionCreateRequest>({
    client: pazeClient1Schema,
    sessionId: s.string(),
    accessToken: s.string(),
    callbackUrlScheme: s.string(),
    intent: intentSchema,
    transactionValue: s.optional(s.lazy(() => transactionValueSchema)),
    transactionType: s.optional(s.lazy(() => transactiontype2Schema)),
    shippingPreference: s.optional(s.lazy(() => shippingpreference1Schema)),
    billingPreference: s.optional(s.lazy(() => billingpreference2Schema)),
    emailAddress: s.optional(s.lazy(() => emailaddressModelSchema)),
    phoneNumber: s.optional(s.lazy(() => phonenumberModelSchema)),
    cobrand: s.optional(s.lazy(() => cobrandSchema)),
    acceptedShippingCountries: s.optional(s.lazy(() => acceptedshippingcountriesSchema)),
    acceptedPaymentCardNetworks: s.optional(s.lazy(() => acceptedpaymentcardnetworksSchema)),
    alwaysEnableCheckout: s.defaulted(s.boolean(), false),
    _keysMap: {
      callbackUrlScheme: "callbackURLScheme",
    },
  });

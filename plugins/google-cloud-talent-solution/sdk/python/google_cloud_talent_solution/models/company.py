class Company(SdkBaseModel):
    """A Company resource represents a company in the service. A company is the entity that owns job postings, that is,
    the hiring entity responsible for employing applicants for the job position."""

    image_uri: Optional[str] = Field(default=UNSET, alias="imageUri")
    """A URI that hosts the employer's company logo."""

    keyword_searchable_job_custom_attributes: Optional[list[str]] = Field(
        default=UNSET, alias="keywordSearchableJobCustomAttributes"
    )
    """This field is deprecated. Please set the searchability of the custom attribute in the Job.custom_attributes going
    forward. A list of keys of filterable Job.custom_attributes, whose corresponding ``string_values`` are used in
    keyword searches. Jobs with ``string_values`` under these specified field keys are returned if any of the values
    match the search keyword. Custom field values with parenthesis, brackets and special symbols are not searchable
    as-is, and those keyword queries must be surrounded by quotes."""

    size: Optional[SizeOrStr] = UNSET
    """The employer's company size."""

    hiring_agency: Optional[bool] = Field(default=UNSET, alias="hiringAgency")
    """Set to true if it is the hiring agency that post jobs for other employers. Defaults to false if not provided."""

    career_site_uri: Optional[str] = Field(default=UNSET, alias="careerSiteUri")
    """The URI to employer's career site or careers page on the employer's web site, for example,
    "https://careers.google.com"."""

    display_name: Optional[str] = Field(default=UNSET, alias="displayName")
    """Required. The display name of the company, for example, "Google LLC"."""

    external_id: Optional[str] = Field(default=UNSET, alias="externalId")
    """Required. Client side company identifier, used to uniquely identify the company. The maximum number of allowed
    characters is 255."""

    derived_info: Optional[CompanyDerivedInfo2] = Field(default=UNSET, alias="derivedInfo")
    """Output only. Derived details about the company."""

    name: Optional[str] = UNSET
    """Required during company update. The resource name for a company. This is generated by the service when a company
    is created. The format is "projects/{project_id}/tenants/{tenant_id}/companies/{company_id}", for example,
    "projects/foo/tenants/bar/companies/baz"."""

    suspended: Optional[bool] = UNSET
    """Output only. Indicates whether a company is flagged to be suspended from public availability by the service when
    job content appears suspicious, abusive, or spammy."""

    website_uri: Optional[str] = Field(default=UNSET, alias="websiteUri")
    """The URI representing the company's primary web site or home page, for example, "https://www.google.com". The
    maximum number of allowed characters is 255."""

    headquarters_address: Optional[str] = Field(default=UNSET, alias="headquartersAddress")
    """The street address of the company's main headquarters, which may be different from the job location. The service
    attempts to geolocate the provided address, and populates a more specific location wherever possible in
    DerivedInfo.headquarters_location."""

    eeo_text: Optional[str] = Field(default=UNSET, alias="eeoText")
    """Equal Employment Opportunity legal disclaimer text to be associated with all jobs, and typically to be displayed
    in all roles. The maximum number of allowed characters is 500."""



import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { apiProxyTypeSchema, type ApiProxyType } from "./api-proxy-type.js";
import {
  googleCloudApigeeV1EntityMetadata3Schema,
  type GoogleCloudApigeeV1EntityMetadata3,
} from "./google-cloud-apigee-v1-entity-metadata3.js";

/** Metadata describing the API proxy */
export type GoogleCloudApigeeV1ApiProxy = {
  /**
   * Output only. Whether this proxy is read-only. A read-only proxy cannot have new revisions
   * created through calls to CreateApiProxyRevision. A proxy is read-only if it was generated by an
   * archive.
   */
  readOnly?: boolean;
  /** Output only. List of revisions defined for the API proxy. */
  revision?: string[];
  /** Output only. Name of the API proxy. */
  name?: string;
  /** Output only. The type of the API proxy. */
  apiProxyType?: ApiProxyType;
  /** Output only. The id of the most recently created revision for this api proxy. */
  latestRevisionId?: string;
  /**
   * Optional. The id of the space this proxy is associated with. Any IAM policies applied to the
   * space will control access to this proxy. To learn how Spaces can be used to manage resources,
   * read the [Apigee Spaces
   * Overview](https://cloud.google.com/apigee/docs/api-platform/system-administration/spaces/apigee-spaces-overview).
   */
  space?: string;
  /** Output only. Metadata describing the API proxy. */
  metaData?: GoogleCloudApigeeV1EntityMetadata3;
  /** User labels applied to this API Proxy. */
  labels?: Record<string, string>;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const googleCloudApigeeV1ApiProxySchema: Schema<GoogleCloudApigeeV1ApiProxy> =
  s.object<GoogleCloudApigeeV1ApiProxy>(
    {
      readOnly: s.optional(s.boolean()),
      revision: s.optional(s.array(s.string())),
      name: s.optional(s.string()),
      apiProxyType: s.optional(s.lazy(() => apiProxyTypeSchema)),
      latestRevisionId: s.optional(s.string()),
      space: s.optional(s.string()),
      metaData: s.optional(s.lazy(() => googleCloudApigeeV1EntityMetadata3Schema)),
      labels: s.optional(s.record(s.string(), s.string())),
    },
    { additionalProperties: s.json() },
  );

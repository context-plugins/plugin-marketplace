import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { transactiontype1Schema, type Transactiontype1 } from "./transactiontype1.js";
import {
  enhancedTransactionDataSchema,
  type EnhancedTransactionData,
} from "./unions/enhanced-transaction-data.js";
import { processingnetwork1Schema, type Processingnetwork1 } from "./unions/processingnetwork1.js";
import { transactionOptionsSchema, type TransactionOptions } from "./unions/transaction-options.js";
import { transactionValue1Schema, type TransactionValue1 } from "./unions/transaction-value1.js";

export type PazeSessionCompleteRequest = {
  /**
   * Session reference identifier generated by the merchant. Must match the value sent in the Paze
   * session create call.
   */
  sessionId: string;
  /**
   * Opaque token issued by the Paze service in the response from the most recent Paze UX
   * interaction.
   */
  code: string;
  /**
   * The Paze OAuth access token returned by the Paze mobile session create call. Used to
   * authenticate the request to Paze.
   */
  accessToken: string;
  /**
   * The type of transaction being completed. PURCHASE for a one-off checkout, CARD_ON_FILE to
   * retain the card for future use, or BOTH.
   */
  transactionType: Transactiontype1;
  /** Client configuration data overriding values configured during merchant onboarding. */
  transactionOptions?: TransactionOptions;
  /**
   * Required when `transactionType` is PURCHASE or BOTH. Must be omitted when `transactionType` is
   * CARD_ON_FILE.
   */
  transactionValue?: TransactionValue1;
  /**
   * Card network to process the transaction on. If not provided, Paze defaults to the network on
   * the front of the card.
   */
  processingNetwork?: Processingnetwork1;
  /** Additional purchase context used by Paze for risk scoring. */
  enhancedTransactionData?: EnhancedTransactionData;
};

export const pazeSessionCompleteRequestSchema: Schema<PazeSessionCompleteRequest> =
  s.object<PazeSessionCompleteRequest>({
    sessionId: s.string(),
    code: s.string(),
    accessToken: s.string(),
    transactionType: transactiontype1Schema,
    transactionOptions: s.optional(s.lazy(() => transactionOptionsSchema)),
    transactionValue: s.optional(s.lazy(() => transactionValue1Schema)),
    processingNetwork: s.optional(s.lazy(() => processingnetwork1Schema)),
    enhancedTransactionData: s.optional(s.lazy(() => enhancedTransactionDataSchema)),
  });

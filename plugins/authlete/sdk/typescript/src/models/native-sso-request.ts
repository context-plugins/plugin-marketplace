import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";

export type NativeSsoRequest = {
  /**
   * The value of this parameter should be: (a) the value of the `jwtAccessToken` parameter in a
   * response from the `/auth/token` API when the value is available, or (b) the value of the
   * `accessToken` parameter in the response from the `/auth/token` API when the `jwtAccessToken`
   * parameter is not available.
   */
  accessToken: string;
  /**
   * The value of this parameter should be the value of the `refreshToken` parameter in a response
   * from the `/auth/token` API.
   */
  refreshToken?: string;
  /**
   * The value that should be used as the value of the `sub` claim of the ID token. This parameter
   * is optional. When omitted, the value of the subject associated with the access token is used.
   */
  sub?: string;
  /**
   * Additional claims that should be embedded in the payload part of the ID token. The format is a
   * JSON object. This parameter is optional.
   */
  claims?: string;
  /**
   * Additional parameters that should be embedded in the JWS header of the ID token. The format is
   * a JSON object. This parameter is optional.
   */
  idtHeaderParams?: string;
  /**
   * The type of the `aud` claim of the ID token being issued. Valid values of this parameter are as
   * follows:
   */
  idTokenAudType?: string;
  /**
   * The device secret. The value of this parameter should be the value of the `deviceSecret`
   * parameter in the response from the `/auth/token` API, if the parameter is present. Otherwise,
   * the authorization server should generate a new device secret and specify it as the value of
   * this parameter.
   */
  deviceSecret: string;
  /**
   * The device secret hash. The specified device secret hash is included as the value of the
   * `ds_hash` claim in the ID token generated by the `/nativesso` API. If the `deviceSecretHash`
   * request parameter is omitted, the value of the `deviceSecret` request parameter is used to
   * compute the hash.
   */
  deviceSecretHash?: string;
};

export const nativeSsoRequestSchema: Schema<NativeSsoRequest> = s.object<NativeSsoRequest>({
  accessToken: s.string(),
  refreshToken: s.optional(s.string()),
  sub: s.optional(s.string()),
  claims: s.optional(s.string()),
  idtHeaderParams: s.optional(s.string()),
  idTokenAudType: s.optional(s.string()),
  deviceSecret: s.string(),
  deviceSecretHash: s.optional(s.string()),
});

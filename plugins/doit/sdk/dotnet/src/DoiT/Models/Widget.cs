using System;
using System.Text.Json.Serialization;
using DoiT.Core.Models;
using DoiT.Models.Enums;

namespace DoiT.Models;

/// <summary>
/// Widget metadata and its latest precomputed cached result.
/// </summary>
public record Widget
{
    /// <summary>
    /// Customer- and tier-specific widget id. This value can vary between customers.
    /// </summary>
    [JsonPropertyName("id")]
    public required string Id { get; init; }

    /// <summary>
    /// Stable customer-facing widget identifier.
    /// </summary>
    [JsonPropertyName("alias")]
    public required string Alias { get; init; }

    /// <summary>
    /// Whether the widget is supplied by DoiT or defined by a customer.
    /// </summary>
    [JsonPropertyName("type")]
    public required TypeDoiTWidgetsBetaApi Type { get; init; }

    /// <summary>
    /// Determines which property is populated in the widget's <c>result</c>.
    /// </summary>
    [JsonPropertyName("kind")]
    public string Kind { get; } = "monetary_metric";

    /// <summary>
    /// Time when the cached result was generated by the background computation.
    /// </summary>
    [JsonPropertyName("generateTime")]
    public required DateTimeOffset GenerateTime { get; init; }

    /// <summary>
    /// Computed widget result. The populated property corresponds to <c>kind</c>.
    /// </summary>
    [JsonPropertyName("result")]
    public required WidgetResult Result { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}

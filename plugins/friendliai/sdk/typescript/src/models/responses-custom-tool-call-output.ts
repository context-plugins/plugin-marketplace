import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { id5Schema, type Id5 } from "./unions/id5.js";
import { output1Schema, type Output1 } from "./unions/output1.js";

export type ResponsesCustomToolCallOutput = {
  /**
   * The type of the custom tool call output. Always `custom_tool_call_output`.
   *
   * @default "custom_tool_call_output"
   */
  type?: "custom_tool_call_output";
  /** The call ID, used to map this custom tool call output to a custom tool call. */
  callId: string;
  /**
   * Text or image output of the custom tool call generated by your code. Can be a string of the
   * output, or an array of content parts (text or image).
   */
  output: Output1;
  /** The unique ID of the custom tool call output. */
  id?: Id5;
};

export const responsesCustomToolCallOutputSchema: Schema<ResponsesCustomToolCallOutput> =
  s.object<ResponsesCustomToolCallOutput>({
    type: s.defaulted(s.literal("custom_tool_call_output"), "custom_tool_call_output"),
    callId: s.string(),
    output: output1Schema,
    id: s.optional(s.lazy(() => id5Schema)),
    _keysMap: {
      callId: "call_id",
    },
  });

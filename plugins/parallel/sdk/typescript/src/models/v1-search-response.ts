import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  usageParallelAiSearchApiSchema,
  type UsageParallelAiSearchApi,
} from "./unions/usage-parallel-ai-search-api.js";
import {
  warningsParallelAiSearchApiSchema,
  type WarningsParallelAiSearchApi,
} from "./unions/warnings-parallel-ai-search-api.js";
import { v1WebSearchResultSchema, type V1WebSearchResult } from "./v1-web-search-result.js";

/** Search response. */
export type V1SearchResponse = {
  /** Search ID. Example: `search_cad0a6d2dec046bd95ae900527d880e7` */
  searchId: string;
  /** A list of search results, ordered by decreasing relevance. */
  results: V1WebSearchResult[];
  /** Warnings for the search request, if any. */
  warnings?: WarningsParallelAiSearchApi;
  /** Usage metrics for the search request. */
  usage?: UsageParallelAiSearchApi;
  /**
   * Session identifier, echoed back from the request if provided, otherwise generated by the
   * server. Should be passed to future search and extract calls made by the agent as part of the
   * same larger task.
   */
  sessionId: string;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const v1SearchResponseSchema: Schema<V1SearchResponse> = s.object<V1SearchResponse>(
  {
    searchId: s.string(),
    results: s.array(s.lazy(() => v1WebSearchResultSchema)),
    warnings: s.optional(s.lazy(() => warningsParallelAiSearchApiSchema)),
    usage: s.optional(s.lazy(() => usageParallelAiSearchApiSchema)),
    sessionId: s.string(),
    _keysMap: {
      searchId: "search_id",
      sessionId: "session_id",
    },
  },
  { additionalProperties: s.json() },
);

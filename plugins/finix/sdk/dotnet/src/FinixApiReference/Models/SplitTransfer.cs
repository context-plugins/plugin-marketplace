using System;
using System.ComponentModel.DataAnnotations;
using System.Text.Json.Serialization;
using FinixApiReference.Core.Models;
using FinixApiReference.Models.Enums;

namespace FinixApiReference.Models;

/// <summary>
/// The <c>Split Transfer</c> resource that was created from a split transacion.
/// </summary>
public record SplitTransfer
{
    /// <summary>
    /// The ID of the resource.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("id")]
    [MinLength(1)]
    public string? Id { get; init; }

    /// <summary>
    /// Timestamp of when the object was created.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("created_at")]
    public DateTimeOffset? CreatedAt { get; init; }

    /// <summary>
    /// Timestamp of when the object was last updated.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("updated_at")]
    public DateTimeOffset? UpdatedAt { get; init; }

    /// <summary>
    /// The total amount that will be debited in cents (e.g. 100 cents to debit $1.00).
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("amount")]
    public long? Amount { get; init; }

    /// <summary>
    /// The minimum amount of the <c>Transfer</c> you'd like to collect as your fee in cents. Defaults to zero (must be less than or equal to the <c>amount</c>).
    /// - If the fees applied by the 'Fee Profile' are <b>*higher</b>* than the value passed in 'fee', 'fee' will not be applied and have no effect.
    /// - If the fees applied by the 'Fee Profile' are <b>*lower</b>* than the value passed in 'fee', an additional fee is be applied, in addition to the fees generated by the <c>Fee Profile</c>.
    ///   - The additional fee is equal to the difference between the value passed in 'fee' and the fees generated by the <c>Fee Profile</c>.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("fee")]
    public long? Fee { get; init; }

    /// <summary>
    /// ISO 4217 3-letter currency code.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("currency")]
    public Currency? Currency { get; init; }

    /// <summary>
    /// The ID of the original parent <c>Transfer</c> that was split.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("parent_transfer_id")]
    public string? ParentTransferId { get; init; }

    /// <summary>
    /// The timestamp of when the <c>Transfer</c> is ready to be settled.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("ready_to_settle_at")]
    public DateTimeOffset? ReadyToSettleAt { get; init; }

    /// <summary>
    /// The type of <c>Split Transfer</c>.
    /// - <c>DEBIT</c>: Standard <c>Split Transfer</c> from a split transaction where the parent <c>Transfer</c> debits the buyer's card.
    /// - <c>DISPUTE_MERCHANT_DEBIT</c>: A <c>Split Transfer</c> created when a <see href="/api/disputes">Dispute</see> pulls funds from merchants proportionally. Created when the parent <see href="/api/disputes/listdisputesadjustments">adjustment transfer</see> has <c>type: DISPUTE</c> and <c>subtype: MERCHANT_DEBIT</c>.
    /// - <c>DISPUTE_MERCHANT_CREDIT</c>: A <c>Split Transfer</c> created when a <c>Dispute</c> is ruled in favor of the <see href="/api/merchants">Merchant</see> and funds are returned proportionally. Created when the parent adjustment <c>Transfer</c> has <c>type: DISPUTE</c> and <c>subtype: MERCHANT_CREDIT</c>.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("type")]
    public Type49? Type { get; init; }

    /// <summary>
    /// The ID of the <c>Merchant</c> resource the <c>Split Transfer</c> was created for and will settle under.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("merchant_id")]
    public string? MerchantId { get; init; }

    /// <summary>
    /// The ID of <c>Identity</c> resource used by the <c>Merchant</c> the <c>Split Transfer</c> was created for.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("identity_id")]
    public string? IdentityId { get; init; }

    /// <summary>
    /// The <c>Fee Profile</c> associated to this <c>Split Transfer</c>.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("fee_profile_id")]
    public string? FeeProfileId { get; init; }

    /// <summary>
    /// ID of the <c>Application</c> the resource was created under.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("application_id")]
    [MinLength(1)]
    public string? ApplicationId { get; init; }

    /// <summary>
    /// Include up to 50 <c>key: value</c> pairs to annotate requests with custom metadata.
    /// - Maximum character length for individual <c>keys</c> is 40.
    /// - Maximum character length for individual <c>values</c> is 500.
    /// (For example, <c>order_number: 25</c>, <c>item_type: produce</c>, <c>department: sales</c>)
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("tags")]
    public object? Tags { get; init; }

    /// <summary>
    /// An object containing link(s) relevant to the request. You can store these links for follow-up requests.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("_links")]
    public Links30? Links { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}

from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .extract_error import ExtractError, ExtractErrorDict
from .usage_item import UsageItem, UsageItemDict
from .v1_extract_result import V1ExtractResult, V1ExtractResultDict
from .warning_model import WarningModel, WarningModelDict


class V1ExtractResponse(SdkBaseModel):
    """Extract response."""

    extract_id: str
    """Extract request ID, e.g. ``extract_cad0a6d2dec046bd95ae900527d880e7``"""

    results: list[V1ExtractResult]
    """Successful extract results."""

    errors: list[ExtractError]
    """Extract errors: requested URLs not in the results."""

    warnings: Optional[list[WarningModel]] = UNSET
    """Warnings for the extract request, if any."""

    usage: Optional[list[UsageItem]] = UNSET
    """Usage metrics for the extract request."""

    session_id: str
    """Session identifier. Echoed back from the request if provided, otherwise generated by the server. Should be passed
    to future search and extract calls made by the agent as part of the same larger task."""


class V1ExtractResponseDict(TypedDict):
    extract_id: str
    results: list[V1ExtractResultDict]
    errors: list[ExtractErrorDict]
    warnings: NotRequired[list[WarningModelDict]]
    usage: NotRequired[list[UsageItemDict]]
    session_id: str

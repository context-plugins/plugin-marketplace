import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { ruleSchema, type Rule } from "./rule.js";
import { tagSchema, type Tag } from "./tag.js";
import { lastClickedSchema, type LastClicked } from "./unions/last-clicked.js";

export type Link = {
  /** The unique ID of the short link. */
  id: string;
  /**
   * The domain of the short link. If not provided, the main domain of the project will be used (or
   * `codeqr.link` if the project has no domains).
   */
  domain: string;
  /** The slug of the short link. If not provided, a random 7-character slug will be generated. */
  key: string;
  url?: string;
  archived?: boolean;
  expiresAt?: string | null;
  expiredUrl: string | null;
  trackConversion?: boolean;
  /** Whether the short link is flexible. @default false */
  flexible?: boolean;
  doIndex?: boolean;
  password: string | null;
  externalId?: string | null;
  proxy?: boolean;
  title: string | null;
  description: string | null;
  image: string | null;
  video: string | null;
  rewrite?: boolean;
  ios: string | null;
  android: string | null;
  geo: Record<string, string> | null;
  rules?: Rule[] | null;
  publicStats?: boolean;
  tagId: string | null;
  tags: Tag[] | null;
  folderId: string | null;
  comments: string | null;
  notificationToken: string | null;
  /**
   * The complete URL of the short link, including the https protocol (for example,
   * `https://codeqr.link/try`).
   */
  shortLink?: string;
  /**
   * The complete QR code URL for the short link (for example,
   * `https://api.codeqr.io/qr?url=https://codeqr.link/try`).
   */
  qrCode?: string;
  utmSource: string | null;
  utmMedium: string | null;
  utmCampaign: string | null;
  utmTerm: string | null;
  utmContent: string | null;
  userId?: string | null;
  /** The ID of the project of the short link. */
  projectId: string;
  /** The number of clicks on the short link. @default 0 */
  clicks?: number;
  /** The number of leads generated by the short link. @default 0 */
  leads?: number;
  /** The number of sales generated by the short link. @default 0 */
  sales?: number;
  /** The amount of the sale generated by the link. @default 0 */
  saleAmount?: number;
  lastClicked?: LastClicked;
  createdAt: string;
  updatedAt: string;
  /** Whether the short link has pre-redirection. @default false */
  preRedirection?: boolean;
  /** The ID of the page to redirect to before the link destination. */
  pageId?: string | null;
  /** The URL of the page to redirect to before the link destination. */
  pageUrl?: string | null;
  /** If the form is mandatory for the page. @default false */
  isFormMandatory?: boolean;
  /** Whether the link is filled or not. @default false */
  filled?: boolean;
  /** Whether this link should be used as a reusable template. @default false */
  useAsTemplate?: boolean;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const linkProperties: s.Shape<Link> = {
  id: s.string(),
  domain: s.string(),
  key: s.string(),
  url: s.optional(s.string()),
  archived: s.optional(s.boolean()),
  expiresAt: s.optionalNullable(s.string()),
  expiredUrl: s.nullable(s.string()),
  trackConversion: s.optional(s.boolean()),
  flexible: s.defaulted(s.boolean(), false),
  doIndex: s.optional(s.boolean()),
  password: s.nullable(s.string()),
  externalId: s.optionalNullable(s.string()),
  proxy: s.optional(s.boolean()),
  title: s.nullable(s.string()),
  description: s.nullable(s.string()),
  image: s.nullable(s.string()),
  video: s.nullable(s.string()),
  rewrite: s.optional(s.boolean()),
  ios: s.nullable(s.string()),
  android: s.nullable(s.string()),
  geo: s.nullable(s.record(s.string(), s.string())),
  rules: s.optionalNullable(s.array(s.lazy(() => ruleSchema))),
  publicStats: s.optional(s.boolean()),
  tagId: s.nullable(s.string()),
  tags: s.nullable(s.array(s.lazy(() => tagSchema))),
  folderId: s.nullable(s.string()),
  comments: s.nullable(s.string()),
  notificationToken: s.nullable(s.string()),
  shortLink: s.optional(s.string()),
  qrCode: s.optional(s.string()),
  utmSource: s.nullable(s.string()),
  utmMedium: s.nullable(s.string()),
  utmCampaign: s.nullable(s.string()),
  utmTerm: s.nullable(s.string()),
  utmContent: s.nullable(s.string()),
  userId: s.optionalNullable(s.string()),
  projectId: s.string(),
  clicks: s.defaulted(s.float64(), 0),
  leads: s.defaulted(s.float64(), 0),
  sales: s.defaulted(s.float64(), 0),
  saleAmount: s.defaulted(s.float64(), 0),
  lastClicked: s.optional(s.lazy(() => lastClickedSchema)),
  createdAt: s.string(),
  updatedAt: s.string(),
  preRedirection: s.defaulted(s.boolean(), false),
  pageId: s.optionalNullable(s.string()),
  pageUrl: s.optionalNullable(s.string()),
  isFormMandatory: s.defaulted(s.boolean(), false),
  filled: s.defaulted(s.boolean(), false),
  useAsTemplate: s.defaulted(s.boolean(), false),
  _keysMap: {
    utmSource: "utm_source",
    utmMedium: "utm_medium",
    utmCampaign: "utm_campaign",
    utmTerm: "utm_term",
    utmContent: "utm_content",
  },
};

export const linkInternalSchema: Schema<Link> = s.object<Link>(linkProperties, {
  additionalProperties: s.json(),
});

export const linkSchema: Schema<Link> = s.lazySchema(() =>
  s.object<Link>(
    {
      ...linkProperties,
      expiredUrl: s.nullable(s.string().check(s.url())),
      shortLink: s.optional(s.string().check(s.url())),
      qrCode: s.optional(s.string().check(s.url())),
    },
    { additionalProperties: s.json() },
  ),
);

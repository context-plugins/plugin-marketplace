import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { streamedChatChoiceDeltaSchema, type StreamedChatChoiceDelta } from "./streamed-chat-choice-delta.js";
import { finishReason21Schema, type FinishReason21 } from "./unions/finish-reason21.js";
import { logprobsSchema, type Logprobs } from "./unions/logprobs.js";

export type StreamedChatChoice = {
  /** The index of the choice in the list of generated choices. */
  index: number;
  logprobs?: Logprobs;
  delta: StreamedChatChoiceDelta;
  /**
   * Termination condition of the generation. `stop` means the API returned the full chat
   * completions generated by the model without running into any limits. `length` means the
   * generation exceeded `max_tokens` or the conversation exceeded the max context length.
   * `tool_calls` means the API has generated tool calls.
   */
  finishReason?: FinishReason21;
};

export const streamedChatChoiceSchema: Schema<StreamedChatChoice> = s.object<StreamedChatChoice>({
  index: s.int(),
  logprobs: s.optional(s.lazy(() => logprobsSchema)),
  delta: streamedChatChoiceDeltaSchema,
  finishReason: s.optional(s.lazy(() => finishReason21Schema)),
  _keysMap: {
    finishReason: "finish_reason",
  },
});

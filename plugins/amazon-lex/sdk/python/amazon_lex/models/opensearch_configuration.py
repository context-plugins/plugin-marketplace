from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .exact_response_fields import ExactResponseFields, ExactResponseFieldsDict


class OpensearchConfiguration(SdkBaseModel):
    domain_endpoint: str = Field(alias="domainEndpoint")
    """The endpoint of the Amazon OpenSearch Service domain."""

    index_name: str = Field(alias="indexName")
    """The name of the Amazon OpenSearch Service index."""

    exact_response: Optional[bool] = Field(default=UNSET, alias="exactResponse")
    """Specifies whether to return an exact response or to return an answer generated by the model using the fields you
    specify from the database."""

    exact_response_fields: Optional[ExactResponseFields] = Field(default=UNSET, alias="exactResponseFields")
    include_fields: Optional[list[str]] = Field(default=UNSET, alias="includeFields")
    """Contains a list of fields from the Amazon OpenSearch Service that the model can use to generate the answer to the
    query."""


class OpensearchConfigurationDict(TypedDict):
    domain_endpoint: str
    index_name: str
    exact_response: NotRequired[bool]
    exact_response_fields: NotRequired[ExactResponseFieldsDict]
    include_fields: NotRequired[list[str]]

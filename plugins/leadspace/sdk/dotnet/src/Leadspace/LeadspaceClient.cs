/// </summary>
public sealed class LeadspaceClient
{
    private readonly RawClient _rawClient;
    private readonly Server _server;
    private readonly AuthSchemes _auth;

    public LeadspaceClient(HttpClient httpClient, LeadspaceClientOptions options)
    {
        _server = new Server(options.Environment, options.Server);
        var queryParameterFactory = new QueryParameterFactory([]);
        var templateParamsFactory = new TemplateParamsFactory([]);
        var urlFactory = new UriFactory(queryParameterFactory, templateParamsFactory);
        var httpStatusPolicy = new HttpStatusPolicy([]);
        var headersFactory = new HeadersFactory([
            new HeaderParam("User-Agent", "LeadspaceClient/4.0 CSharp"),
            new HeaderParam("X-APIMatic-Lang", "CSharp"),
            new HeaderParam("X-APIMatic-Package-Version", "4.0"),
            new HeaderParam("X-APIMatic-Gen-Version", "4.0.0"),
            new HeaderParam("X-APIMatic-OS", RuntimeEnvironment.Os),
            new HeaderParam("X-APIMatic-Runtime", RuntimeEnvironment.Runtime),
        ]);
        var resiliencePipelineFactory = new ResiliencePipelineFactory(options.Retry, options.TimeProvider);
        var httpLogger = new HttpLogger(
            options.Logging.WithEnvironmentDefaults("LEADSPACE_LOG"),
            "LeadspaceClient",
            options.TimeProvider);
        var responseContexts = new ResponseContextFactory(options.TimeProvider, options.StreamReadTimeout);
        _rawClient =
            new RawClient(
                httpClient,
                urlFactory,
                httpStatusPolicy,
                headersFactory,
                resiliencePipelineFactory,
                httpLogger,
                options.Hooks,
                responseContexts);
        _auth = new AuthSchemes(options);
    }

    /// <summary>
    /// OAuth 2.0 token issuance and refresh
    /// </summary>
    public Authorization Authorization => field ??= new Authorization(_rawClient, _server);

    /// <summary>
    /// Bulk account expansion into net-new contacts
    /// </summary>
    public Discovery Discovery => field ??= new Discovery(_rawClient, _server, _auth);

    /// <summary>
    /// Single and bulk person and company enrichment
    /// </summary>
    public Enrichment Enrichment => field ??= new Enrichment(_rawClient, _server, _auth);

    /// <summary>
    /// Buyer-intent scoring and refresh
    /// </summary>
    public Intent Intent => field ??= new Intent(_rawClient, _server, _auth);

    /// <summary>
    /// Polling for asynchronous discovery results
    /// </summary>
    public Results Results => field ??= new Results(_rawClient, _server, _auth);
}

using System.Collections.Generic;
using System.Text.Json.Serialization;
using Apigee.Core.Models;

namespace Apigee.Models;

/// <summary>
/// API proxy revision.
/// </summary>
public record GoogleCloudApigeeV1ApiProxyRevision
{
    /// <summary>
    /// Version of the API proxy configuration schema to which the API proxy conforms. Currently, the only supported value is 4.0 (<c>majorVersion.minorVersion</c>). This setting may be used in the future to track the evolution of the API proxy format.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("configurationVersion")]
    public GoogleCloudApigeeV1ConfigVersion3? ConfigurationVersion { get; init; }

    /// <summary>
    /// List of resource files included in the API proxy revision.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("resourceFiles")]
    public GoogleCloudApigeeV1ResourceFiles3? ResourceFiles { get; init; }

    /// <summary>
    /// Output only. This field will be marked as true if revision contains any policies marked as extensible.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("hasExtensiblePolicy")]
    public bool? HasExtensiblePolicy { get; init; }

    /// <summary>
    /// List of IntegrationEndpoints in the '/integration-endpoints' directory of the API proxy. This is a 'manifest' setting designed to provide visibility into the contents of the API proxy.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("integrationEndpoints")]
    public IReadOnlyList<string>? IntegrationEndpoints { get; init; }

    /// <summary>
    /// Output only. The archive that generated this proxy revision. This field is only present on proxy revisions that were generated by an archive. Proxies generated by archives cannot be updated, deleted, or deployed to other environments. Format: <c>organizations/*/environments/*/archiveDeployments/*</c>
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("archive")]
    public string? Archive { get; init; }

    /// <summary>
    /// List of TargetServers referenced in any TargetEndpoint in the API proxy. Typically, you will see this element only when the API proxy was created using the Edge UI. This is a 'manifest' setting designed to provide visibility into the contents of the API proxy.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("targetServers")]
    public IReadOnlyList<string>? TargetServers { get; init; }

    /// <summary>
    /// Description of the API proxy revision.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("description")]
    public string? Description { get; init; }

    /// <summary>
    /// Name of the API proxy.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("name")]
    public string? Name { get; init; }

    /// <summary>
    /// List of TargetEndpoints in the <c>/targets</c> directory of the API proxy. Typically, this element is included only when the API proxy was created using the Edge UI. This is a 'manifest' setting designed to provide visibility into the contents of the API proxy.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("targetEndpoints")]
    public IReadOnlyList<string>? TargetEndpoints { get; init; }

    /// <summary>
    /// Time that the API proxy revision was last modified in milliseconds since epoch.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("lastModifiedAt")]
    public string? LastModifiedAt { get; init; }

    /// <summary>
    /// Type. Set to <c>Application</c>. Maintained for compatibility with the Apigee Edge API.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("type")]
    public string? Type { get; init; }

    /// <summary>
    /// List of the shared flows included in the API proxy revision.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("sharedFlows")]
    public IReadOnlyList<string>? SharedFlows { get; init; }

    /// <summary>
    /// Revision number, app name, and organization for the API proxy.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("contextInfo")]
    public string? ContextInfo { get; init; }

    /// <summary>
    /// List of the resources included in the API proxy revision formatted as "{type}://{name}".
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("resources")]
    public IReadOnlyList<string>? Resources { get; init; }

    /// <summary>
    /// List of proxy names included in the API proxy revision.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("proxies")]
    public IReadOnlyList<string>? Proxies { get; init; }

    /// <summary>
    /// Metadata describing the API proxy revision as a key-value map.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("entityMetaDataAsProperties")]
    public IReadOnlyDictionary<string, string>? EntityMetaDataAsProperties { get; init; }

    /// <summary>
    /// List of the teams included in the API proxy revision.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("teams")]
    public IReadOnlyList<string>? Teams { get; init; }

    /// <summary>
    /// List of policy names included in the API proxy revision..
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("policies")]
    public IReadOnlyList<string>? Policies { get; init; }

    /// <summary>
    /// Time that the API proxy revision was created in milliseconds since epoch.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("createdAt")]
    public string? CreatedAt { get; init; }

    /// <summary>
    /// Output only. Whether this proxy revision is detected as an MCP (Model Context Protocol) proxy. A proxy revision is identified as MCP if it has a proxy endpoint with the <c>/mcp</c> base path that routes to the MCP target URL.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("mcp")]
    public bool? Mcp { get; init; }

    /// <summary>
    /// API proxy revision.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("revision")]
    public string? Revision { get; init; }

    /// <summary>
    /// List of the targets included in the API proxy revision.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("targets")]
    public IReadOnlyList<string>? Targets { get; init; }

    /// <summary>
    /// Base URL of the API proxy.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("basepaths")]
    public IReadOnlyList<string>? Basepaths { get; init; }

    /// <summary>
    /// OpenAPI Specification that is associated with the API proxy. The value is set to a URL or to a path in the specification store.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("spec")]
    public string? Spec { get; init; }

    /// <summary>
    /// List of ProxyEndpoints in the <c>/proxies</c> directory of the API proxy. Typically, this element is included only when the API proxy was created using the Edge UI. This is a 'manifest' setting designed to provide visibility into the contents of the API proxy.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("proxyEndpoints")]
    public IReadOnlyList<string>? ProxyEndpoints { get; init; }

    /// <summary>
    /// Human-readable name of the API proxy.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("displayName")]
    public string? DisplayName { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}

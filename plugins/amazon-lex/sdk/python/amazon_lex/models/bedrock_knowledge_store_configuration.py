from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .bedrock_knowledge_store_exact_response_fields import (
    BedrockKnowledgeStoreExactResponseFields,
    BedrockKnowledgeStoreExactResponseFieldsDict,
)


class BedrockKnowledgeStoreConfiguration(SdkBaseModel):
    bedrock_knowledge_base_arn: str = Field(alias="bedrockKnowledgeBaseArn")
    """The base ARN of the knowledge base used."""

    exact_response: Optional[bool] = Field(default=UNSET, alias="exactResponse")
    """Specifies whether to return an exact response, or to return an answer generated by the model, using the fields
    you specify from the database."""

    exact_response_fields: Optional[BedrockKnowledgeStoreExactResponseFields] = Field(
        default=UNSET, alias="exactResponseFields"
    )


class BedrockKnowledgeStoreConfigurationDict(TypedDict):
    bedrock_knowledge_base_arn: str
    exact_response: NotRequired[bool]
    exact_response_fields: NotRequired[BedrockKnowledgeStoreExactResponseFieldsDict]

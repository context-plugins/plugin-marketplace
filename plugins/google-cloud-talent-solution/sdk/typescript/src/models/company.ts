import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { companyDerivedInfo2Schema, type CompanyDerivedInfo2 } from "./company-derived-info2.js";
import { sizeSchema, type Size } from "./size.js";

/**
 * A Company resource represents a company in the service. A company is the entity that owns job
 * postings, that is, the hiring entity responsible for employing applicants for the job position.
 */
export type Company = {
  /** A URI that hosts the employer's company logo. */
  imageUri?: string;
  /**
   * This field is deprecated. Please set the searchability of the custom attribute in the
   * Job.custom_attributes going forward. A list of keys of filterable Job.custom_attributes, whose
   * corresponding `string_values` are used in keyword searches. Jobs with `string_values` under
   * these specified field keys are returned if any of the values match the search keyword. Custom
   * field values with parenthesis, brackets and special symbols are not searchable as-is, and those
   * keyword queries must be surrounded by quotes.
   *
   * @deprecated
   */
  keywordSearchableJobCustomAttributes?: string[];
  /** The employer's company size. */
  size?: Size;
  /**
   * Set to true if it is the hiring agency that post jobs for other employers. Defaults to false if
   * not provided.
   */
  hiringAgency?: boolean;
  /**
   * The URI to employer's career site or careers page on the employer's web site, for example,
   * "https://careers.google.com".
   */
  careerSiteUri?: string;
  /** Required. The display name of the company, for example, "Google LLC". */
  displayName?: string;
  /**
   * Required. Client side company identifier, used to uniquely identify the company. The maximum
   * number of allowed characters is 255.
   */
  externalId?: string;
  /** Output only. Derived details about the company. */
  derivedInfo?: CompanyDerivedInfo2;
  /**
   * Required during company update. The resource name for a company. This is generated by the
   * service when a company is created. The format is
   * "projects/{project_id}/tenants/{tenant_id}/companies/{company_id}", for example,
   * "projects/foo/tenants/bar/companies/baz".
   */
  name?: string;
  /**
   * Output only. Indicates whether a company is flagged to be suspended from public availability by
   * the service when job content appears suspicious, abusive, or spammy.
   */
  suspended?: boolean;
  /**
   * The URI representing the company's primary web site or home page, for example,
   * "https://www.google.com". The maximum number of allowed characters is 255.
   */
  websiteUri?: string;
  /**
   * The street address of the company's main headquarters, which may be different from the job
   * location. The service attempts to geolocate the provided address, and populates a more specific
   * location wherever possible in DerivedInfo.headquarters_location.
   */
  headquartersAddress?: string;
  /**
   * Equal Employment Opportunity legal disclaimer text to be associated with all jobs, and
   * typically to be displayed in all roles. The maximum number of allowed characters is 500.
   */
  eeoText?: string;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const companySchema: Schema<Company> = s.object<Company>(
  {
    imageUri: s.optional(s.string()),
    keywordSearchableJobCustomAttributes: s.optional(s.array(s.string())),
    size: s.optional(s.lazy(() => sizeSchema)),
    hiringAgency: s.optional(s.boolean()),
    careerSiteUri: s.optional(s.string()),
    displayName: s.optional(s.string()),
    externalId: s.optional(s.string()),
    derivedInfo: s.optional(s.lazy(() => companyDerivedInfo2Schema)),
    name: s.optional(s.string()),
    suspended: s.optional(s.boolean()),
    websiteUri: s.optional(s.string()),
    headquartersAddress: s.optional(s.string()),
    eeoText: s.optional(s.string()),
  },
  { additionalProperties: s.json() },
);

import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { errorSchema, type Error } from "./unions/error.js";
import { incompleteDetailsSchema, type IncompleteDetails } from "./unions/incomplete-details.js";
import { model21Schema, type Model21 } from "./unions/model21.js";
import { responsesOutputItemSchema, type ResponsesOutputItem } from "./unions/responses-output-item.js";
import { status31Schema, type Status31 } from "./unions/status31.js";
import { usage4Schema, type Usage4 } from "./unions/usage4.js";

export type ResponsesSuccess = {
  /** Unique identifier for this response. */
  id: string;
  /** The object type of this resource - always set to `response`. @default "response" */
  object?: "response";
  /** Unix timestamp (in seconds) of when this response was created. */
  createdAt: number;
  /** An error object returned when the model fails to generate a Response. */
  error?: Error;
  /**
   * The status of the response generation. One of `completed`, `failed`, `in_progress`,
   * `cancelled`, `queued`, or `incomplete`.
   */
  status?: Status31;
  /** An array of content items generated by the model. */
  output: ResponsesOutputItem[];
  /**
   * Represents token usage details including input tokens, output tokens, a breakdown of output
   * tokens, and the total tokens used.
   */
  usage?: Usage4;
  /** Details about why the response is incomplete. */
  incompleteDetails?: IncompleteDetails;
  /** Model ID used to generate the response. */
  model?: Model21;
};

export const responsesSuccessSchema: Schema<ResponsesSuccess> = s.object<ResponsesSuccess>({
  id: s.string(),
  object: s.defaulted(s.literal("response"), "response"),
  createdAt: s.int(),
  error: s.optional(s.lazy(() => errorSchema)),
  status: s.optional(s.lazy(() => status31Schema)),
  output: s.array(s.lazy(() => responsesOutputItemSchema)),
  usage: s.optional(s.lazy(() => usage4Schema)),
  incompleteDetails: s.optional(s.lazy(() => incompleteDetailsSchema)),
  model: s.optional(s.lazy(() => model21Schema)),
  _keysMap: {
    createdAt: "created_at",
    incompleteDetails: "incomplete_details",
  },
});

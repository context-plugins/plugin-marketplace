export class LeadspaceClient {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;
  #authorization?: Authorization;
  #discovery?: Discovery;
  #enrichment?: Enrichment;
  #intent?: Intent;
  #results?: Results;

  constructor(options: ClientOptions = {}) {
    this.#rawClient = new RawClient({
      ...buildCoreClientOptions(options, "LEADSPACE_LOG"),
      defaultHeaders: [
        { name: "User-Agent", value: "LeadspaceClient/4.0.0 TypeScript", schema: s.string() },
        { name: "X-APIMatic-Lang", value: "TypeScript", schema: s.string() },
        { name: "X-APIMatic-Package-Version", value: "4.0.0", schema: s.string() },
        { name: "X-APIMatic-Gen-Version", value: "4.0.0", schema: s.string() },
        { name: "X-APIMatic-OS", value: host.operatingSystem(), schema: s.optional(s.string()) },
        { name: "X-APIMatic-Runtime", value: host.runtimeDescription(), schema: s.optional(s.string()) },
      ],
      defaultQuery: [],
      defaultPathParams: [],
    });

    this.#servers = buildServers(options);

    this.#auth = buildAuthSchemes(options);
  }

  /**
   * OAuth 2.0 token issuance and refresh
   */
  get authorization(): Authorization {
    return (this.#authorization ??= new Authorization(this.#rawClient, this.#servers));
  }

  /**
   * Bulk account expansion into net-new contacts
   */
  get discovery(): Discovery {
    return (this.#discovery ??= new Discovery(this.#rawClient, this.#servers, this.#auth));
  }

  /**
   * Single and bulk person and company enrichment
   */
  get enrichment(): Enrichment {
    return (this.#enrichment ??= new Enrichment(this.#rawClient, this.#servers, this.#auth));
  }

  /**
   * Buyer-intent scoring and refresh
   */
  get intent(): Intent {
    return (this.#intent ??= new Intent(this.#rawClient, this.#servers, this.#auth));
  }

  /**
   * Polling for asynchronous discovery results
   */
  get results(): Results {
    return (this.#results ??= new Results(this.#rawClient, this.#servers, this.#auth));
  }
}

from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .google_cloud_apihub_v1_deployment_metadata import (
    GoogleCloudApihubV1DeploymentMetadata,
    GoogleCloudApihubV1DeploymentMetadataDict,
)
from .google_cloud_apihub_v1_spec_metadata import GoogleCloudApihubV1SpecMetadata, GoogleCloudApihubV1SpecMetadataDict
from .google_cloud_apihub_v1_version3 import GoogleCloudApihubV1Version3, GoogleCloudApihubV1Version3Dict


class GoogleCloudApihubV1VersionMetadata(SdkBaseModel):
    """The metadata associated with a version of the API resource."""

    original_update_time: Optional[str] = Field(default=UNSET, alias="originalUpdateTime")
    """Required. Timestamp indicating when the version was last updated at the source."""

    original_id: Optional[str] = Field(default=UNSET, alias="originalId")
    """Optional. The unique identifier of the version in the system where it was originally created."""

    specs: Optional[list[GoogleCloudApihubV1SpecMetadata]] = UNSET
    """Optional. The specs associated with this version. Note that an API version can be associated with multiple
    specs."""

    version: Optional[GoogleCloudApihubV1Version3] = UNSET
    """Required. Represents a version of the API resource in API hub. The ID of the version will be generated by Hub."""

    deployments: Optional[list[GoogleCloudApihubV1DeploymentMetadata]] = UNSET
    """Optional. The deployments linked to this API version. Note: A particular API version could be deployed to
    multiple deployments (for dev deployment, UAT deployment, etc.)"""

    original_create_time: Optional[str] = Field(default=UNSET, alias="originalCreateTime")
    """Optional. Timestamp indicating when the version was created at the source."""


class GoogleCloudApihubV1VersionMetadataDict(TypedDict):
    original_update_time: NotRequired[str]
    original_id: NotRequired[str]
    specs: NotRequired[list[GoogleCloudApihubV1SpecMetadataDict]]
    version: NotRequired[GoogleCloudApihubV1Version3Dict]
    deployments: NotRequired[list[GoogleCloudApihubV1DeploymentMetadataDict]]
    original_create_time: NotRequired[str]

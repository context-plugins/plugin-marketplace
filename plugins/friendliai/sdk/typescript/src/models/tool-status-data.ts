import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { nameSchema, type Name } from "./name.js";
import { status8Schema, type Status8 } from "./status8.js";
import { toolStatusParameterSchema, type ToolStatusParameter } from "./tool-status-parameter.js";
import { error4Schema, type Error4 } from "./unions/error4.js";
import { filesSchema, type Files } from "./unions/files.js";
import { message1Schema, type Message1 } from "./unions/message1.js";
import { resultSchema, type Result } from "./unions/result.js";

export type ToolStatusData = {
  /** The ID of the tool call. */
  toolCallId: string;
  /** The name of the built-in tool. */
  name: Name;
  /** Indicates the current execution status of the tool. */
  status: Status8;
  parameters: ToolStatusParameter[];
  /** The output from the tool's execution. */
  result?: Result;
  files?: Files;
  /** Message generated by the tool's execution. */
  message?: Message1;
  error?: Error4;
  /** The Unix timestamp (in seconds) for when the event occurred. */
  timestamp: number;
};

export const toolStatusDataSchema: Schema<ToolStatusData> = s.object<ToolStatusData>({
  toolCallId: s.string(),
  name: nameSchema,
  status: status8Schema,
  parameters: s.array(s.lazy(() => toolStatusParameterSchema)),
  result: s.optional(s.lazy(() => resultSchema)),
  files: s.optional(s.lazy(() => filesSchema)),
  message: s.optional(s.lazy(() => message1Schema)),
  error: s.optional(s.lazy(() => error4Schema)),
  timestamp: s.float64(),
  _keysMap: {
    toolCallId: "tool_call_id",
  },
});

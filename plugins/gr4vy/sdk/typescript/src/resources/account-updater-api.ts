/**
 * Schedule stored cards for an account update.
 */
export class AccountUpdaterApi {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * Create account updater job
   *
   * @remarks
   * Schedule one or more stored cards for an account update.
   *
   * @returns A scheduled account updater job when one or more payment methods were scheduled for
   * update.
   *
   * @throws {@link AccountUpdaterApi.CreateAccountUpdaterJobError} when the API answers with an
   * error status — narrow on `err.payload.kind`
   *
   * @throws {@link Gr4VyError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  createAccountUpdaterJob(
    request: AccountUpdaterApi.CreateAccountUpdaterJobRequest,
    options?: RequestOptions,
  ): ApiPromise<AccountUpdaterJob, AccountUpdaterApi.CreateAccountUpdaterJobError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        urlTemplate: this.#servers.default("/account-updater/jobs"),
        auth: this.#auth.oAuth2PasswordBearer,
        pathParams: [],
        query: [],
        headers: [
          {
            name: "x-gr4vy-merchant-account-id",
            value: request.xGr4VyMerchantAccountId,
            schema: s.optional(s.lazy(() => xGr4VyMerchantAccountIdSchema)),
          },
          { name: "Idempotency-Key", value: uuid(), schema: s.string() },
        ],
        body: { kind: "json", value: request.body, schema: accountUpdaterJobCreateSchema },
      },
      {
        success: { kind: "json", schema: accountUpdaterJobSchema },
        errorFactory: AccountUpdaterApi.CreateAccountUpdaterJobError,
      },
      options,
    );
  }
}


import type { AuthSchemes } from "../auth-schemes.js";
import { ApiError, type Declared, type Undeclared } from "../core/api-error.js";
import type { ApiPromise } from "../core/api-promise.js";
import type { RequestOptions } from "../core/api-request.js";
import { anyAuth } from "../core/auth/schemes.js";
import type { RawClient } from "../core/raw-client.js";
import type { ErrorDecoders } from "../core/response-decoder.js";
import * as s from "../core/validation/index.js";
import {
  v2WalletsApplepaySessionsRequestSchema,
  type V2WalletsApplepaySessionsRequest,
} from "../models/v2-wallets-applepay-sessions-request.js";
import type { Servers } from "../servers.js";

/**
 * Operations related to the Wallets API
 */
export class WalletsApi {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * Request Apple Pay payment session
   *
   * @remarks
   * When integrating Apple Pay in your own checkout on the web, you need to [provide merchant
   * validation](https://developer.apple.com/documentation/apple_pay_on_the_web/apple_pay_js_api/providing_merchant_validation).
   * This is normally done using Apple's [Requesting an Apple Pay
   * Session](https://developer.apple.com/documentation/apple_pay_on_the_web/apple_pay_js_api/requesting_an_apple_pay_payment_session).
   * The merchant validation proves to Apple that a validated merchant is calling the Apple Pay
   * Javascript APIs.
   *
   * To integrate Apple Pay via Mollie, you will have to call the Mollie API instead of Apple's API.
   * The response of this API call can then be passed as-is to the completion method,
   * `completeMerchantValidation`.
   *
   * Before requesting an Apple Pay Payment Session, you must place the domain validation file on
   * your server at: `https://[domain]/.well-known/apple-developer-merchantid-domain-association`.
   * Without this file, it will not be possible to use Apple Pay on your domain.
   *
   * Each new transaction requires a new payment session object. Merchant session objects are not
   * reusable, and they expire after five minutes.
   *
   * Payment sessions cannot be requested directly from the browser. The request must be sent from
   * your server. For the full documentation, see the official [Apple Pay JS
   * API](https://developer.apple.com/documentation/apple_pay_on_the_web/apple_pay_js_api)
   * documentation.
   *
   * @returns The Apple Pay payment session object generated by Apple. This object, as mentioned in
   * the Apple's Documentation, is opaque, so we are not defining a response schema.
   *
   * @throws {@link WalletsApi.RequestApplePayPaymentSessionError} when the API answers with an
   * error status — narrow on `err.payload.kind`
   *
   * @throws {@link MollieApiError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  requestApplePayPaymentSession(
    request: WalletsApi.RequestApplePayPaymentSessionRequest,
    options?: RequestOptions,
  ): ApiPromise<undefined, WalletsApi.RequestApplePayPaymentSessionError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        urlTemplate: this.#servers.default("/v2/wallets/applepay/sessions"),
        auth: anyAuth(this.#auth.apiKey, this.#auth.advancedAccessToken, this.#auth.oAuth),
        pathParams: [],
        query: [],
        headers: [{ name: "idempotency-key", value: request.idempotencyKey, schema: s.optional(s.string()) }],
        body: {
          kind: "json",
          value: request.body,
          schema: s.optional(s.lazy(() => v2WalletsApplepaySessionsRequestSchema)),
        },
      },
      {
        success: { kind: "empty" },
        errorFactory: WalletsApi.RequestApplePayPaymentSessionError,
      },
      options,
    );
  }
}

export namespace WalletsApi {
  export type RequestApplePayPaymentSessionRequest = {
    /** A unique key to ensure idempotent requests. This key should be a UUID v4 string. */
    idempotencyKey?: string;
    body?: V2WalletsApplepaySessionsRequest;
  };

  export class RequestApplePayPaymentSessionError extends ApiError {
    declare readonly payload: Declared<"error422", undefined> | Declared<"error429", undefined> | Undeclared;

    static readonly errors: ErrorDecoders<RequestApplePayPaymentSessionError> = [
      { on: 422, kind: "error422", decode: { kind: "empty" } },
      { on: 429, kind: "error429", decode: { kind: "empty" } },
    ];
  }
}

from __future__ import annotations

from typing import Any

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel


class ManifestTask(SdkBaseModel):
    """One task definition from the control channel's ``tasks.list`` reply.

    All schemas are JSON Schemas generated by the SDK: ``args`` describes the task function's parameters (what a stored
    task's ``args`` must satisfy); ``input``/``returns`` describe the agent's I/O types when the task declares them."""

    id: str
    description: Optional[str] = UNSET
    args: Optional[Any] = UNSET
    input: Optional[Any] = UNSET
    returns: Optional[Any] = UNSET


class ManifestTaskDict(TypedDict):
    id: str
    description: NotRequired[str]
    args: NotRequired[Any]
    input: NotRequired[Any]
    returns: NotRequired[Any]

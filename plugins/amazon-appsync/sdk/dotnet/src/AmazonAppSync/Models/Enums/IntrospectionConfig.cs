/// Sets the value of the GraphQL API to enable (ENABLED) or disable (DISABLED) introspection. If no value is provided, the introspection configuration will be set to ENABLED by default. This field will produce an error if the operation attempts to use the introspection feature while this field is disabled. For more information about introspection, see GraphQL introspection.
/// </summary>
[JsonConverter(typeof(StringEnumConverter<IntrospectionConfig>))]
public sealed record IntrospectionConfig : OpenStringEnum<IntrospectionConfig>
{
    private IntrospectionConfig(string value) : base(value)
    {
    }

    public static readonly IntrospectionConfig Enabled = new("ENABLED");

    public static readonly IntrospectionConfig Disabled = new("DISABLED");

    public TResult Match<TResult>(Func<TResult> onEnabled, Func<TResult> onDisabled, Func<string, TResult> otherwise) =>
        this switch
        {
            _ when this == Enabled => onEnabled(),
            _ when this == Disabled => onDisabled(),
            _ => otherwise(Value)
        };

    public void Match(Action onEnabled, Action onDisabled, Action<string> otherwise)
    {
        if (this == Enabled) onEnabled();
        else if (this == Disabled) onDisabled();
        else otherwise(Value);
    }
}

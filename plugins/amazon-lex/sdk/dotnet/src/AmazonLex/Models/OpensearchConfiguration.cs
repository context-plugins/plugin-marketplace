using System.Collections.Generic;
using System.Text.Json.Serialization;
using AmazonLex.Core.Models;

namespace AmazonLex.Models;

public record OpensearchConfiguration
{
    /// <summary>
    /// The endpoint of the Amazon OpenSearch Service domain.
    /// </summary>
    [JsonPropertyName("domainEndpoint")]
    public required string DomainEndpoint { get; init; }

    /// <summary>
    /// The name of the Amazon OpenSearch Service index.
    /// </summary>
    [JsonPropertyName("indexName")]
    public required string IndexName { get; init; }

    /// <summary>
    /// Specifies whether to return an exact response or to return an answer generated by the model using the fields you specify from the database.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("exactResponse")]
    public bool? ExactResponse { get; init; }

    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("exactResponseFields")]
    public ExactResponseFields? ExactResponseFields { get; init; }

    /// <summary>
    /// Contains a list of fields from the Amazon OpenSearch Service that the model can use to generate the answer to the query.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("includeFields")]
    public IReadOnlyList<string>? IncludeFields { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}

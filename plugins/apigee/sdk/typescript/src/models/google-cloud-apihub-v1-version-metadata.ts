import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  googleCloudApihubV1DeploymentMetadataSchema,
  type GoogleCloudApihubV1DeploymentMetadata,
} from "./google-cloud-apihub-v1-deployment-metadata.js";
import {
  googleCloudApihubV1SpecMetadataSchema,
  type GoogleCloudApihubV1SpecMetadata,
} from "./google-cloud-apihub-v1-spec-metadata.js";
import {
  googleCloudApihubV1Version3Schema,
  type GoogleCloudApihubV1Version3,
} from "./google-cloud-apihub-v1-version3.js";

/** The metadata associated with a version of the API resource. */
export type GoogleCloudApihubV1VersionMetadata = {
  /** Required. Timestamp indicating when the version was last updated at the source. */
  originalUpdateTime?: string;
  /**
   * Optional. The unique identifier of the version in the system where it was originally created.
   */
  originalId?: string;
  /**
   * Optional. The specs associated with this version. Note that an API version can be associated
   * with multiple specs.
   */
  specs?: GoogleCloudApihubV1SpecMetadata[];
  /**
   * Required. Represents a version of the API resource in API hub. The ID of the version will be
   * generated by Hub.
   */
  version?: GoogleCloudApihubV1Version3;
  /**
   * Optional. The deployments linked to this API version. Note: A particular API version could be
   * deployed to multiple deployments (for dev deployment, UAT deployment, etc.)
   */
  deployments?: GoogleCloudApihubV1DeploymentMetadata[];
  /** Optional. Timestamp indicating when the version was created at the source. */
  originalCreateTime?: string;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const googleCloudApihubV1VersionMetadataSchema: Schema<GoogleCloudApihubV1VersionMetadata> =
  s.object<GoogleCloudApihubV1VersionMetadata>(
    {
      originalUpdateTime: s.optional(s.string()),
      originalId: s.optional(s.string()),
      specs: s.optional(s.array(s.lazy(() => googleCloudApihubV1SpecMetadataSchema))),
      version: s.optional(s.lazy(() => googleCloudApihubV1Version3Schema)),
      deployments: s.optional(s.array(s.lazy(() => googleCloudApihubV1DeploymentMetadataSchema))),
      originalCreateTime: s.optional(s.string()),
    },
    { additionalProperties: s.json() },
  );

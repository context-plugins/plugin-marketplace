using System;
using System.Text.Json.Serialization;
using AmazonLex.Core.Enum;

namespace AmazonLex.Models.Enums;

/// <summary>
/// The priority level of the recommendation. Valid Values: High | Medium | Low
/// </summary>
[JsonConverter(typeof(StringEnumConverter<Priority>))]
public sealed record Priority : OpenStringEnum<Priority>
{
    private Priority(string value) : base(value)
    {
    }

    public static readonly Priority High = new("High");

    public static readonly Priority Medium = new("Medium");

    public static readonly Priority Low = new("Low");

    public TResult Match<TResult>(Func<TResult> onHigh,
        Func<TResult> onMedium,
        Func<TResult> onLow,
        Func<string, TResult> otherwise) =>
        this switch
        {
            _ when this == High => onHigh(),
            _ when this == Medium => onMedium(),
            _ when this == Low => onLow(),
            _ => otherwise(Value)
        };

    public void Match(Action onHigh, Action onMedium, Action onLow, Action<string> otherwise)
    {
        if (this == High) onHigh();
        else if (this == Medium) onMedium();
        else if (this == Low) onLow();
        else otherwise(Value);
    }
}

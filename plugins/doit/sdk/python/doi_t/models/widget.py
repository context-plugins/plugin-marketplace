from __future__ import annotations

from typing import Literal

from pydantic import Field
from typing_extensions import TypedDict

from ..core import RFC3339DateTime, SdkBaseModel
from .enums.type_doi_t_widgets_beta_api import TypeDoiTWidgetsBetaApiOrStr
from .widget_result import WidgetResult, WidgetResultDict


class Widget(SdkBaseModel):
    """Widget metadata and its latest precomputed cached result."""

    id: str
    """Customer- and tier-specific widget id. This value can vary between customers."""

    alias: str
    """Stable customer-facing widget identifier."""

    type_: TypeDoiTWidgetsBetaApiOrStr = Field(alias="type")
    """Whether the widget is supplied by DoiT or defined by a customer."""

    kind: Literal["monetary_metric"] = "monetary_metric"
    """Determines which property is populated in the widget's ``result``."""

    generate_time: RFC3339DateTime = Field(alias="generateTime")
    """Time when the cached result was generated by the background computation."""

    result: WidgetResult
    """Computed widget result. The populated property corresponds to ``kind``."""


class WidgetDict(TypedDict):
    id: str
    alias: str
    type_: TypeDoiTWidgetsBetaApiOrStr
    kind: Literal["monetary_metric"]
    generate_time: RFC3339DateTime
    result: WidgetResultDict

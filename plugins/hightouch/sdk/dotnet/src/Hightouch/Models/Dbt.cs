using System.Text.Json.Serialization;
using Hightouch.Core.Models;

namespace Hightouch.Models;

/// <summary>
/// Query that is based on a dbt model
/// </summary>
public record Dbt
{
    /// <summary>
    /// Unique ID of the model assigned by dbt (usually some combination of the schema and table name)
    /// </summary>
    [JsonPropertyName("dbtUniqueId")]
    public required string DbtUniqueId { get; init; }

    /// <summary>
    /// Compiled SQL in the dbt model
    /// </summary>
    [JsonPropertyName("compiledSql")]
    public required string CompiledSql { get; init; }

    /// <summary>
    /// Raw SQL in the dbt model
    /// </summary>
    [JsonPropertyName("rawSql")]
    public required string RawSql { get; init; }

    /// <summary>
    /// Name of the database containing the generated table
    /// </summary>
    [JsonPropertyName("database")]
    public required string Database { get; init; }

    /// <summary>
    /// Name of the schema containing the generated table
    /// </summary>
    [JsonPropertyName("schema")]
    public required string Schema { get; init; }

    /// <summary>
    /// Name of the table generated by the dbt model
    /// </summary>
    [JsonPropertyName("name")]
    public required string Name { get; init; }

    /// <summary>
    /// Model id that refer to a dbt model
    /// </summary>
    [JsonPropertyName("modelId")]
    public required double ModelId { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}

import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";

/** Specifies Kerberos related configuration. */
export type KerberosConfig = {
  /**
   * Optional. The Cloud Storage URI of the truststore file used for SSL encryption. If not
   * provided, the service will provide a self-signed certificate.
   */
  truststoreUri?: string;
  /**
   * Optional. The remote realm the on-cluster KDC will trust, should the user enable cross realm
   * trust.
   */
  crossRealmTrustRealm?: string;
  /**
   * Optional. The Cloud Storage URI of a KMS encrypted file containing the password to the user
   * provided keystore. For the self-signed certificate, this password is generated by the service.
   */
  keystorePasswordUri?: string;
  /**
   * Optional. The Cloud Storage URI of a KMS encrypted file containing the master key of the KDC
   * database.
   */
  kdcDbKeyUri?: string;
  /**
   * Optional. The lifetime of the ticket granting ticket, in hours. If not specified, or user
   * specifies 0, then default value 10 will be used.
   */
  tgtLifetimeHours?: number;
  /**
   * Optional. The Cloud Storage URI of a KMS encrypted file containing the password to the user
   * provided key. For the self-signed certificate, this password is generated by the service.
   */
  keyPasswordUri?: string;
  /**
   * Optional. The KDC (IP or hostname) for the remote trusted realm in a cross realm trust
   * relationship.
   */
  crossRealmTrustKdc?: string;
  /**
   * Optional. The Cloud Storage URI of a KMS encrypted file containing the root principal password.
   */
  rootPrincipalPasswordUri?: string;
  /**
   * Optional. The Cloud Storage URI of the keystore file used for SSL encryption. If not provided,
   * the service will provide a self-signed certificate.
   */
  keystoreUri?: string;
  /**
   * Optional. The Cloud Storage URI of a KMS encrypted file containing the password to the user
   * provided truststore. For the self-signed certificate, this password is generated by the
   * service.
   */
  truststorePasswordUri?: string;
  /**
   * Optional. The name of the on-cluster Kerberos realm. If not specified, the uppercased domain of
   * hostnames will be the realm.
   */
  realm?: string;
  /**
   * Optional. The Cloud Storage URI of a KMS encrypted file containing the shared password between
   * the on-cluster Kerberos realm and the remote trusted realm, in a cross realm trust
   * relationship.
   */
  crossRealmTrustSharedPasswordUri?: string;
  /** Optional. The URI of the KMS key used to encrypt sensitive files. */
  kmsKeyUri?: string;
  /**
   * Optional. The admin server (IP or hostname) for the remote trusted realm in a cross realm trust
   * relationship.
   */
  crossRealmTrustAdminServer?: string;
  /**
   * Optional. Flag to indicate whether to Kerberize the cluster (default: false). Set this field to
   * true to enable Kerberos on a cluster.
   */
  enableKerberos?: boolean;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const kerberosConfigSchema: Schema<KerberosConfig> = s.object<KerberosConfig>(
  {
    truststoreUri: s.optional(s.string()),
    crossRealmTrustRealm: s.optional(s.string()),
    keystorePasswordUri: s.optional(s.string()),
    kdcDbKeyUri: s.optional(s.string()),
    tgtLifetimeHours: s.optional(s.int()),
    keyPasswordUri: s.optional(s.string()),
    crossRealmTrustKdc: s.optional(s.string()),
    rootPrincipalPasswordUri: s.optional(s.string()),
    keystoreUri: s.optional(s.string()),
    truststorePasswordUri: s.optional(s.string()),
    realm: s.optional(s.string()),
    crossRealmTrustSharedPasswordUri: s.optional(s.string()),
    kmsKeyUri: s.optional(s.string()),
    crossRealmTrustAdminServer: s.optional(s.string()),
    enableKerberos: s.optional(s.boolean()),
  },
  { additionalProperties: s.json() },
);

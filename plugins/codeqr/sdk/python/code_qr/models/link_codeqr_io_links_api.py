from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .rule import Rule, RuleDict
from .tag_model import TagModel, TagModelDict


class LinkCodeqrIoLinksApi(SdkBaseModel):
    id: str
    """The unique ID of the short link."""

    domain: str
    """The domain of the short link. If not provided, the main domain of the project will be used (or ``codeqr.link`` if
    the project has no domains)."""

    key: str
    """The slug of the short link. If not provided, a random 7-character slug will be generated."""

    url: str
    """The destination URL of the short link."""

    archived: bool = False
    """Whether the short link is archived."""

    expires_at: str | None = Field(alias="expiresAt")
    """The date and time when the short link will expire in ISO-8601 format. Must be in the future."""

    expired_url: str | None = Field(alias="expiredUrl")
    """The URL to redirect to when the short link expires."""

    track_conversion: bool = Field(default=False, alias="trackConversion")
    """[BETA] Whether to track conversions for the short link."""

    flexible: bool = False
    """Whether the short link is flexible."""

    do_index: bool = Field(default=False, alias="doIndex")
    """Whether search engines can index the short link."""

    password: str | None
    """The password required to access the short link destination URL."""

    external_id: str | None = Field(alias="externalId")
    """This is the ID of the link in your database."""

    proxy: bool = False
    """Whether the short link uses the custom link preview feature."""

    title: str | None
    """The title of the short link generated via ``api.codeqr.io/metatags``. Will be used for custom link preview if
    ``proxy`` is true."""

    description: str | None
    """The description of the short link generated via ``api.codeqr.io/metatags``. Will be used for custom link preview
    if ``proxy`` is true."""

    image: str | None
    """The image of the short link generated via ``api.codeqr.io/metatags``. Will be used for custom link preview if
    ``proxy`` is true."""

    video: str | None
    """The video of the short link."""

    rewrite: bool = False
    """Whether the short link uses link cloaking."""

    ios: str | None
    """The iOS destination URL for the short link for iOS device targeting."""

    android: str | None
    """The Android destination URL for the short link for Android device targeting."""

    geo: dict[str, str] | None
    """Geographic targeting information for the short link in JSON format ``{[COUNTRY]: https://example.com }``. Learn
    more: https://codeqr.link/geo"""

    rules: list[Rule] | None
    """Smart rules for conditional destination routing by request attribute."""

    public_stats: bool = Field(default=False, alias="publicStats")
    """Whether the short link statistics are publicly accessible."""

    tag_id: str | None = Field(alias="tagId")
    """[DEPRECATED (use ``tags`` instead)]: The unique ID of the tag assigned to the short link."""

    tags: list[TagModel] | None
    """The tags assigned to the short link."""

    folder_id: str | None = Field(alias="folderId")
    """The unique ID of the folder assigned to the short link."""

    comments: str | None
    """The comments for the short link."""

    notification_token: str | None = Field(alias="notificationToken")
    """The notification token of the short link."""

    short_link: Optional[str] = Field(default=UNSET, alias="shortLink")
    """The complete URL of the short link, including the https protocol (for example, ``https://codeqr.link/try``)."""

    qr_code: Optional[str] = Field(default=UNSET, alias="qrCode")
    """The complete QR code URL for the short link (for example,
    ``https://api.codeqr.io/qr?url=https://codeqr.link/try``)."""

    utm_source: str | None
    """The UTM source of the short link."""

    utm_medium: str | None
    """The UTM medium of the short link."""

    utm_campaign: str | None
    """The UTM campaign of the short link."""

    utm_term: str | None
    """The UTM term of the short link."""

    utm_content: str | None
    """The UTM content of the short link."""

    user_id: str = Field(alias="userId")
    """The ID of the user who created the short link."""

    project_id: str = Field(alias="projectId")
    """The ID of the project of the short link."""

    clicks: float = 0.0
    """The number of clicks on the short link."""

    leads: float = 0.0
    """The number of leads generated by the short link."""

    sales: float = 0.0
    """The number of sales generated by the short link."""

    sale_amount: float = Field(default=0.0, alias="saleAmount")
    """The amount of the sale generated by the link."""

    last_clicked: str | None = Field(alias="lastClicked")
    """The date and time when the short link was last clicked."""

    created_at: str = Field(alias="createdAt")
    """The date and time when the short link was created."""

    updated_at: str = Field(alias="updatedAt")
    """The date and time when the short link was last updated."""

    pre_redirection: bool = Field(default=False, alias="preRedirection")
    """Whether the short link has pre-redirection."""

    page_id: OptionalNullable[str] = Field(default=UNSET, alias="pageId")
    """The ID of the page to redirect to before the link destination."""

    page_url: OptionalNullable[str] = Field(default=UNSET, alias="pageUrl")
    """The URL of the page to redirect to before the link destination."""

    is_form_mandatory: bool = Field(default=False, alias="isFormMandatory")
    """If the form is mandatory for the page."""

    filled: bool = False
    """Whether the link is filled or not."""

    use_as_template: bool = Field(default=False, alias="useAsTemplate")
    """Whether this link should be used as a reusable template."""


class LinkCodeqrIoLinksApiDict(TypedDict):
    id: str
    domain: str
    key: str
    url: str
    archived: bool
    expires_at: str | None
    expired_url: str | None
    track_conversion: bool
    flexible: bool
    do_index: bool
    password: str | None
    external_id: str | None
    proxy: bool
    title: str | None
    description: str | None
    image: str | None
    video: str | None
    rewrite: bool
    ios: str | None
    android: str | None
    geo: dict[str, str] | None
    rules: list[RuleDict] | None
    public_stats: bool
    tag_id: str | None
    tags: list[TagModelDict] | None
    folder_id: str | None
    comments: str | None
    notification_token: str | None
    short_link: NotRequired[str]
    qr_code: NotRequired[str]
    utm_source: str | None
    utm_medium: str | None
    utm_campaign: str | None
    utm_term: str | None
    utm_content: str | None
    user_id: str
    project_id: str
    clicks: float
    leads: float
    sales: float
    sale_amount: float
    last_clicked: str | None
    created_at: str
    updated_at: str
    pre_redirection: bool
    page_id: NotRequired[str | None]
    page_url: NotRequired[str | None]
    is_form_mandatory: bool
    filled: bool
    use_as_template: bool

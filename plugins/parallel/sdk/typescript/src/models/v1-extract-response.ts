import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { extractErrorSchema, type ExtractError } from "./extract-error.js";
import {
  usageParallelAiExtractApiSchema,
  type UsageParallelAiExtractApi,
} from "./unions/usage-parallel-ai-extract-api.js";
import { warningsSchema, type Warnings } from "./unions/warnings.js";
import { v1ExtractResultSchema, type V1ExtractResult } from "./v1-extract-result.js";

/** Extract response. */
export type V1ExtractResponse = {
  /** Extract request ID, e.g. `extract_cad0a6d2dec046bd95ae900527d880e7` */
  extractId: string;
  /** Successful extract results. */
  results: V1ExtractResult[];
  /** Extract errors: requested URLs not in the results. */
  errors: ExtractError[];
  /** Warnings for the extract request, if any. */
  warnings?: Warnings;
  /** Usage metrics for the extract request. */
  usage?: UsageParallelAiExtractApi;
  /**
   * Session identifier. Echoed back from the request if provided, otherwise generated by the
   * server. Should be passed to future search and extract calls made by the agent as part of the
   * same larger task.
   */
  sessionId: string;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const v1ExtractResponseSchema: Schema<V1ExtractResponse> = s.object<V1ExtractResponse>(
  {
    extractId: s.string(),
    results: s.array(s.lazy(() => v1ExtractResultSchema)),
    errors: s.array(s.lazy(() => extractErrorSchema)),
    warnings: s.optional(s.lazy(() => warningsSchema)),
    usage: s.optional(s.lazy(() => usageParallelAiExtractApiSchema)),
    sessionId: s.string(),
    _keysMap: {
      extractId: "extract_id",
      sessionId: "session_id",
    },
  },
  { additionalProperties: s.json() },
);

import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { blockSchema, type Block } from "./block.js";
import { checksumBeforeSchema, type ChecksumBefore } from "./unions/checksum-before.js";
import { oldModeSchema, type OldMode } from "./unions/old-mode.js";

export type DiffFile = {
  /** Number of lines added in this file. */
  addedLines: number;
  /** Array of diff blocks (hunks) showing changed line ranges in this file. */
  blocks: Block[];
  /** Percentage of lines in the file that changed. */
  changedPercentage?: number;
  /** Checksum of the new file. */
  checksumAfter?: string;
  /** Checksum of the original file. May be an array for combined diffs. */
  checksumBefore?: ChecksumBefore;
  /** File mode of the deleted file, present when the file was deleted. */
  deletedFileMode?: string;
  /** Number of lines deleted in this file. */
  deletedLines: number;
  /**
   * If <code>true</code>, this file is a binary file and the diff content is not shown. Otherwise,
   * <code>false</code>.
   */
  isBinary?: boolean;
  /**
   * If <code>true</code>, this is a combined diff (merge commit). Otherwise, <code>false</code>.
   */
  isCombined: boolean;
  /**
   * If <code>true</code>, this file was copied from another path. Otherwise, <code>false</code>.
   */
  isCopy?: boolean;
  /** If <code>true</code>, this file was deleted in the commit. Otherwise, <code>false</code>. */
  isDeleted?: boolean;
  /** If <code>true</code>, this diff was generated by Git. Otherwise, <code>false</code>. */
  isGitDiff: boolean;
  /** If <code>true</code>, this file was added in the commit. Otherwise, <code>false</code>. */
  isNew?: boolean;
  /** If <code>true</code>, this file was renamed. Otherwise, <code>false</code>. */
  isRename?: boolean;
  /**
   * If <code>true</code>, the diff was truncated because it exceeded the line limit. Otherwise,
   * <code>false</code>.
   */
  isTooBig?: boolean;
  /**
   * File extension of the changed file specified in <code>newName</code>, used for syntax
   * highlighting. Omitted for files without an extension.
   */
  language?: string;
  /** Combined file mode when both old and new modes are the same. */
  mode?: string;
  /** File mode of the new file, present when the file was added. */
  newFileMode?: string;
  /** File mode of the new file. */
  newMode?: string;
  /** New file path after the change. */
  newName: string;
  /** File mode of the original file. May be an array for combined diffs. */
  oldMode?: OldMode;
  /** Original file path before the change. */
  oldName: string;
  /** Percentage of lines in the file that are unchanged. */
  unchangedPercentage?: number;
};

export const diffFileSchema: Schema<DiffFile> = s.object<DiffFile>({
  addedLines: s.int(),
  blocks: s.array(s.lazy(() => blockSchema)),
  changedPercentage: s.optional(s.float64()),
  checksumAfter: s.optional(s.string()),
  checksumBefore: s.optional(s.lazy(() => checksumBeforeSchema)),
  deletedFileMode: s.optional(s.string()),
  deletedLines: s.int(),
  isBinary: s.optional(s.boolean()),
  isCombined: s.boolean(),
  isCopy: s.optional(s.boolean()),
  isDeleted: s.optional(s.boolean()),
  isGitDiff: s.boolean(),
  isNew: s.optional(s.boolean()),
  isRename: s.optional(s.boolean()),
  isTooBig: s.optional(s.boolean()),
  language: s.optional(s.string()),
  mode: s.optional(s.string()),
  newFileMode: s.optional(s.string()),
  newMode: s.optional(s.string()),
  newName: s.string(),
  oldMode: s.optional(s.lazy(() => oldModeSchema)),
  oldName: s.string(),
  unchangedPercentage: s.optional(s.float64()),
});

import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { finishReason31Schema, type FinishReason31 } from "./unions/finish-reason31.js";
import { logprobs3Schema, type Logprobs3 } from "./unions/logprobs3.js";
import { tokenSchema, type Token } from "./unions/token.js";

export type StreamedCompletionsChoice = {
  /** The index of the choice in the list of generated choices. */
  index: number;
  /** Generated text output. */
  text: string;
  logprobs?: Logprobs3;
  /**
   * Termination condition of the generation. `stop` means the API returned the full completions
   * generated by the model without running into any limits. `length` means the generation exceeded
   * `max_tokens` or the conversation exceeded the max context length.
   */
  finishReason?: FinishReason31;
  /** The token. */
  token?: Token;
};

export const streamedCompletionsChoiceSchema: Schema<StreamedCompletionsChoice> =
  s.object<StreamedCompletionsChoice>({
    index: s.int(),
    text: s.string(),
    logprobs: s.optional(s.lazy(() => logprobs3Schema)),
    finishReason: s.optional(s.lazy(() => finishReason31Schema)),
    token: s.optional(s.lazy(() => tokenSchema)),
    _keysMap: {
      finishReason: "finish_reason",
    },
  });

export class Portfolio {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * Convert Positions
   *
   * @remarks
   * Convert the margin product of an open position
   *
   * @returns Successful
   *
   * @throws {@link Portfolio.ConvertPositionsError} when the API answers with an error status —
   * narrow on `err.payload.kind`
   *
   * @throws {@link UpstoxError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  convertPositions(
    request: Portfolio.ConvertPositionsRequest,
    options?: RequestOptions,
  ): ApiPromise<ConvertPositionResponse, Portfolio.ConvertPositionsError> {
    return this.#rawClient.execute(
      {
        method: "PUT",
        urlTemplate: this.#servers.default("/v2/portfolio/convert-position"),
        auth: this.#auth.oauth2,
        pathParams: [],
        query: [],
        headers: [{ name: "Idempotency-Key", value: uuid(), schema: s.string() }],
        body: { kind: "json", value: request.body, schema: convertPositionRequestSchema },
      },
      {
        success: { kind: "json", schema: convertPositionResponseSchema },
        errorFactory: Portfolio.ConvertPositionsError,
      },
      options,
    );
  }

  /**
   * Get Holdings
   *
   * @remarks
   * Fetches the holdings which the user has bought/sold in previous trading sessions.
   *
   * @returns Successful
   *
   * @throws {@link Portfolio.GetHoldingsError} when the API answers with an error status — narrow
   * on `err.payload.kind`
   *
   * @throws {@link UpstoxError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  getHoldings(options?: RequestOptions): ApiPromise<GetHoldingsResponse, Portfolio.GetHoldingsError> {
    return this.#rawClient.execute(
      {
        method: "GET",
        urlTemplate: this.#servers.default("/v2/portfolio/long-term-holdings"),
        auth: this.#auth.oauth2,
        pathParams: [],
        query: [],
        headers: [],
        body: { kind: "empty" },
      },
      {
        success: { kind: "json", schema: getHoldingsResponseSchema },
        errorFactory: Portfolio.GetHoldingsError,
      },
      options,
    );
  }

  /**
   * Get MTF positions
   *
   * @remarks
   * This API allows you to get MTF positions.
   *
   * @returns Successful
   *
   * @throws {@link Portfolio.GetMtfPositionsError} when the API answers with an error status —
   * narrow on `err.payload.kind`
   *
   * @throws {@link UpstoxError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  getMtfPositions(options?: RequestOptions): ApiPromise<GetPositionResponse, Portfolio.GetMtfPositionsError> {
    return this.#rawClient.execute(
      {
        method: "GET",
        urlTemplate: this.#servers.default("/v3/portfolio/mtf-positions"),
        auth: this.#auth.oauth2,
        pathParams: [],
        query: [],
        headers: [],
        body: { kind: "empty" },
      },
      {
        success: { kind: "json", schema: getPositionResponseSchema },
        errorFactory: Portfolio.GetMtfPositionsError,
      },
      options,
    );
  }

  /**
   * Get Positions
   *
   * @remarks
   * Fetches the current positions for the user for the current day.
   *
   * @returns Successful
   *
   * @throws {@link Portfolio.GetPositionsError} when the API answers with an error status — narrow
   * on `err.payload.kind`
   *
   * @throws {@link UpstoxError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  getPositions(options?: RequestOptions): ApiPromise<GetPositionResponse, Portfolio.GetPositionsError> {
    return this.#rawClient.execute(
      {
        method: "GET",
        urlTemplate: this.#servers.default("/v2/portfolio/short-term-positions"),
        auth: this.#auth.oauth2,
        pathParams: [],
        query: [],
        headers: [],
        body: { kind: "empty" },
      },
      {
        success: { kind: "json", schema: getPositionResponseSchema },
        errorFactory: Portfolio.GetPositionsError,
      },
      options,
    );
  }
}


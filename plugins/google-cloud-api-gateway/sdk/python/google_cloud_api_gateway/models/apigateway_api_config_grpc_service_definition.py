from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .apigateway_api_config_file import ApigatewayApiConfigFile, ApigatewayApiConfigFileDict
from .apigateway_api_config_file1 import ApigatewayApiConfigFile1, ApigatewayApiConfigFile1Dict


class ApigatewayApiConfigGrpcServiceDefinition(SdkBaseModel):
    """A gRPC service definition."""

    file_descriptor_set: Optional[ApigatewayApiConfigFile1] = Field(default=UNSET, alias="fileDescriptorSet")
    """Input only. File descriptor set, generated by protoc. To generate, use protoc with imports and source info
    included. For an example test.proto file, the following command would put the value in a new file named out.pb. $
    protoc --include_imports --include_source_info test.proto -o out.pb"""

    source: Optional[list[ApigatewayApiConfigFile]] = UNSET
    """Optional. Uncompiled proto files associated with the descriptor set, used for display purposes (server-side
    compilation is not supported). These should match the inputs to 'protoc' command used to generate
    file_descriptor_set."""


class ApigatewayApiConfigGrpcServiceDefinitionDict(TypedDict):
    file_descriptor_set: NotRequired[ApigatewayApiConfigFile1Dict]
    source: NotRequired[list[ApigatewayApiConfigFileDict]]

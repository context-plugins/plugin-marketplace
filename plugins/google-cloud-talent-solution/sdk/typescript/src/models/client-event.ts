import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { jobEventSchema, type JobEvent } from "./job-event.js";

/**
 * An event issued when an end user interacts with the application that implements Cloud Talent
 * Solution. Providing this information improves the quality of results for the API clients,
 * enabling the service to perform optimally. The number of events sent must be consistent with
 * other calls, such as job searches, issued to the service by the client.
 */
export type ClientEvent = {
  /** Required. A unique identifier, generated by the client application. */
  eventId?: string;
  /** Required. The timestamp of the event. */
  createTime?: string;
  /**
   * Notes about the event provided by recruiters or other users, for example, feedback on why a job
   * was bookmarked.
   */
  eventNotes?: string;
  /**
   * Strongly recommended for the best service experience. A unique ID generated in the API
   * responses. It can be found in ResponseMetadata.request_id.
   */
  requestId?: string;
  /**
   * An event issued when a job seeker interacts with the application that implements Cloud Talent
   * Solution.
   */
  jobEvent?: JobEvent;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const clientEventSchema: Schema<ClientEvent> = s.object<ClientEvent>(
  {
    eventId: s.optional(s.string()),
    createTime: s.optional(s.string()),
    eventNotes: s.optional(s.string()),
    requestId: s.optional(s.string()),
    jobEvent: s.optional(s.lazy(() => jobEventSchema)),
  },
  { additionalProperties: s.json() },
);

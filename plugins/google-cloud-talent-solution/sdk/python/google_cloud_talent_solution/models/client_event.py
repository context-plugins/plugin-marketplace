from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .job_event import JobEvent, JobEventDict


class ClientEvent(SdkBaseModel):
    """An event issued when an end user interacts with the application that implements Cloud Talent Solution. Providing
    this information improves the quality of results for the API clients, enabling the service to perform optimally. The
    number of events sent must be consistent with other calls, such as job searches, issued to the service by the
    client."""

    event_id: Optional[str] = Field(default=UNSET, alias="eventId")
    """Required. A unique identifier, generated by the client application."""

    create_time: Optional[str] = Field(default=UNSET, alias="createTime")
    """Required. The timestamp of the event."""

    event_notes: Optional[str] = Field(default=UNSET, alias="eventNotes")
    """Notes about the event provided by recruiters or other users, for example, feedback on why a job was
    bookmarked."""

    request_id: Optional[str] = Field(default=UNSET, alias="requestId")
    """Strongly recommended for the best service experience. A unique ID generated in the API responses. It can be found
    in ResponseMetadata.request_id."""

    job_event: Optional[JobEvent] = Field(default=UNSET, alias="jobEvent")
    """An event issued when a job seeker interacts with the application that implements Cloud Talent Solution."""


class ClientEventDict(TypedDict):
    event_id: NotRequired[str]
    create_time: NotRequired[str]
    event_notes: NotRequired[str]
    request_id: NotRequired[str]
    job_event: NotRequired[JobEventDict]

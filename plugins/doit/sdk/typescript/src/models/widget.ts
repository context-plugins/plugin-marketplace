import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { typeDoiTWidgetsBetaApiSchema, type TypeDoiTWidgetsBetaApi } from "./type-doi-twidgets-beta-api.js";
import { widgetResultInternalSchema, widgetResultSchema, type WidgetResult } from "./widget-result.js";

/** Widget metadata and its latest precomputed cached result. */
export type Widget = {
  /** Customer- and tier-specific widget id. This value can vary between customers. */
  id: string;
  /** Stable customer-facing widget identifier. */
  alias: string;
  /** Whether the widget is supplied by DoiT or defined by a customer. */
  type: TypeDoiTWidgetsBetaApi;
  /** Determines which property is populated in the widget's `result`. @default "monetary_metric" */
  kind?: "monetary_metric";
  /** Time when the cached result was generated by the background computation. */
  generateTime: Date;
  /** Computed widget result. The populated property corresponds to `kind`. */
  result: WidgetResult;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const widgetProperties: s.Shape<Widget> = {
  id: s.string(),
  alias: s.string(),
  type: typeDoiTWidgetsBetaApiSchema,
  kind: s.defaulted(s.literal("monetary_metric"), "monetary_metric"),
  generateTime: s.dateTime(),
  result: widgetResultInternalSchema,
};

export const widgetInternalSchema: Schema<Widget> = s.object<Widget>(widgetProperties, {
  additionalProperties: s.json(),
});

export const widgetSchema: Schema<Widget> = s.lazySchema(() =>
  s.object<Widget>(
    {
      ...widgetProperties,
      result: widgetResultSchema,
    },
    { additionalProperties: s.json() },
  ),
);

using System.Text.Json.Serialization;
using GoogleCloudDataproc.Core.Models;

namespace GoogleCloudDataproc.Models;

/// <summary>
/// Specifies Kerberos related configuration.
/// </summary>
public record KerberosConfig
{
    /// <summary>
    /// Optional. The Cloud Storage URI of the truststore file used for SSL encryption. If not provided, the service will provide a self-signed certificate.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("truststoreUri")]
    public string? TruststoreUri { get; init; }

    /// <summary>
    /// Optional. The remote realm the on-cluster KDC will trust, should the user enable cross realm trust.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("crossRealmTrustRealm")]
    public string? CrossRealmTrustRealm { get; init; }

    /// <summary>
    /// Optional. The Cloud Storage URI of a KMS encrypted file containing the password to the user provided keystore. For the self-signed certificate, this password is generated by the service.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("keystorePasswordUri")]
    public string? KeystorePasswordUri { get; init; }

    /// <summary>
    /// Optional. The Cloud Storage URI of a KMS encrypted file containing the master key of the KDC database.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("kdcDbKeyUri")]
    public string? KdcDbKeyUri { get; init; }

    /// <summary>
    /// Optional. The lifetime of the ticket granting ticket, in hours. If not specified, or user specifies 0, then default value 10 will be used.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("tgtLifetimeHours")]
    public int? TgtLifetimeHours { get; init; }

    /// <summary>
    /// Optional. The Cloud Storage URI of a KMS encrypted file containing the password to the user provided key. For the self-signed certificate, this password is generated by the service.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("keyPasswordUri")]
    public string? KeyPasswordUri { get; init; }

    /// <summary>
    /// Optional. The KDC (IP or hostname) for the remote trusted realm in a cross realm trust relationship.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("crossRealmTrustKdc")]
    public string? CrossRealmTrustKdc { get; init; }

    /// <summary>
    /// Optional. The Cloud Storage URI of a KMS encrypted file containing the root principal password.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("rootPrincipalPasswordUri")]
    public string? RootPrincipalPasswordUri { get; init; }

    /// <summary>
    /// Optional. The Cloud Storage URI of the keystore file used for SSL encryption. If not provided, the service will provide a self-signed certificate.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("keystoreUri")]
    public string? KeystoreUri { get; init; }

    /// <summary>
    /// Optional. The Cloud Storage URI of a KMS encrypted file containing the password to the user provided truststore. For the self-signed certificate, this password is generated by the service.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("truststorePasswordUri")]
    public string? TruststorePasswordUri { get; init; }

    /// <summary>
    /// Optional. The name of the on-cluster Kerberos realm. If not specified, the uppercased domain of hostnames will be the realm.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("realm")]
    public string? Realm { get; init; }

    /// <summary>
    /// Optional. The Cloud Storage URI of a KMS encrypted file containing the shared password between the on-cluster Kerberos realm and the remote trusted realm, in a cross realm trust relationship.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("crossRealmTrustSharedPasswordUri")]
    public string? CrossRealmTrustSharedPasswordUri { get; init; }

    /// <summary>
    /// Optional. The URI of the KMS key used to encrypt sensitive files.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("kmsKeyUri")]
    public string? KmsKeyUri { get; init; }

    /// <summary>
    /// Optional. The admin server (IP or hostname) for the remote trusted realm in a cross realm trust relationship.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("crossRealmTrustAdminServer")]
    public string? CrossRealmTrustAdminServer { get; init; }

    /// <summary>
    /// Optional. Flag to indicate whether to Kerberize the cluster (default: false). Set this field to true to enable Kerberos on a cluster.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("enableKerberos")]
    public bool? EnableKerberos { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}

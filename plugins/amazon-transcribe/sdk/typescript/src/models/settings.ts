import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { vocabularyFilterMethodSchema, type VocabularyFilterMethod } from "./vocabulary-filter-method.js";

export type Settings = {
  /**
   * The name of the custom vocabulary you want to use in your transcription job request. This name
   * is case sensitive, cannot contain spaces, and must be unique within an Amazon Web Services
   * account.
   */
  vocabularyName?: string;
  /**
   * Enables speaker partitioning (diarization) in your transcription output. Speaker partitioning
   * labels the speech from individual speakers in your media file. If you enable ShowSpeakerLabels
   * in your request, you must also include MaxSpeakerLabels. For more information, see Partitioning
   * speakers (diarization).
   */
  showSpeakerLabels?: boolean;
  /**
   * Specify the maximum number of speakers you want to partition in your media. Note that if your
   * media contains more speakers than the specified number, multiple speakers are treated as a
   * single speaker. If you specify the MaxSpeakerLabels field, you must set the ShowSpeakerLabels
   * field to true.
   */
  maxSpeakerLabels?: number;
  /**
   * Enables channel identification in multi-channel audio. Channel identification transcribes the
   * audio on each channel independently, then appends the output for each channel into one
   * transcript. For more information, see Transcribing multi-channel audio.
   */
  channelIdentification?: boolean;
  /**
   * To include alternative transcriptions within your transcription output, include
   * ShowAlternatives in your transcription request. If you have multi-channel audio and do not
   * enable channel identification, your audio is transcribed in a continuous manner and your
   * transcript does not separate the speech by channel. If you include ShowAlternatives, you must
   * also include MaxAlternatives, which is the maximum number of alternative transcriptions you
   * want Amazon Transcribe to generate. For more information, see Alternative transcriptions.
   */
  showAlternatives?: boolean;
  /**
   * Indicate the maximum number of alternative transcriptions you want Amazon Transcribe to include
   * in your transcript. If you select a number greater than the number of alternative
   * transcriptions generated by Amazon Transcribe, only the actual number of alternative
   * transcriptions are included. If you include MaxAlternatives in your request, you must also
   * include ShowAlternatives with a value of true. For more information, see Alternative
   * transcriptions.
   */
  maxAlternatives?: number;
  /**
   * The name of the custom vocabulary filter you want to use in your transcription job request.
   * This name is case sensitive, cannot contain spaces, and must be unique within an Amazon Web
   * Services account. Note that if you include VocabularyFilterName in your request, you must also
   * include VocabularyFilterMethod.
   */
  vocabularyFilterName?: string;
  /**
   * Specify how you want your custom vocabulary filter applied to your transcript. To replace words
   * with ***, choose mask. To delete words, choose remove. To flag words without changing them,
   * choose tag.
   */
  vocabularyFilterMethod?: VocabularyFilterMethod;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const settingsSchema: Schema<Settings> = s.object<Settings>(
  {
    vocabularyName: s.optional(s.string()),
    showSpeakerLabels: s.optional(s.boolean()),
    maxSpeakerLabels: s.optional(s.int()),
    channelIdentification: s.optional(s.boolean()),
    showAlternatives: s.optional(s.boolean()),
    maxAlternatives: s.optional(s.int()),
    vocabularyFilterName: s.optional(s.string()),
    vocabularyFilterMethod: s.optional(s.lazy(() => vocabularyFilterMethodSchema)),
    _keysMap: {
      vocabularyName: "VocabularyName",
      showSpeakerLabels: "ShowSpeakerLabels",
      maxSpeakerLabels: "MaxSpeakerLabels",
      channelIdentification: "ChannelIdentification",
      showAlternatives: "ShowAlternatives",
      maxAlternatives: "MaxAlternatives",
      vocabularyFilterName: "VocabularyFilterName",
      vocabularyFilterMethod: "VocabularyFilterMethod",
    },
  },
  { additionalProperties: s.json() },
);

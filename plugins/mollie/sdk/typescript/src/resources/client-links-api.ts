import type { AuthSchemes } from "../auth-schemes.js";
import { ApiError, type Declared, type Undeclared } from "../core/api-error.js";
import type { ApiPromise } from "../core/api-promise.js";
import type { RequestOptions } from "../core/api-request.js";
import type { RawClient } from "../core/raw-client.js";
import type { ErrorDecoders } from "../core/response-decoder.js";
import * as s from "../core/validation/index.js";
import { clientLinkRequestSchema, type ClientLinkRequest } from "../models/client-link-request.js";
import type { Servers } from "../servers.js";

/**
 * Operations related to the Client Links API
 */
export class ClientLinksApi {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * Create client link
   *
   * @remarks
   * Link a new or existing organization to your OAuth application, in effect creating a new client.
   * The response contains a `clientLink` where you should redirect your customer to.
   *
   * ## Redirecting the Customer
   *
   * The `clientLink` URL behaves similarly to a standard OAuth authorization URL. Therefore, after
   * receiving the `clientLink` URL in the API response, you need to **append the following query
   * parameters** *before* redirecting the customer:
   *
   * * `client_id` _string (required)_
   *
   * The client ID you received when you registered your OAuth app. The ID starts with `app_`. For
   * example: `app_abc123qwerty`.
   *
   * * `state` _string (required)_
   *
   * A random string **generated by your app** to prevent CSRF attacks. This will be reflected in
   * the `state` query parameter when the user returns to the `redirect_uri` after authorizing your
   * app.
   *
   * * `scope` _string (required)_
   *
   * A space-separated list of permissions ('scopes') your app requires. See the [permissions
   * list](https://docs.mollie.com/docs/permissions) for more information about the available
   * scopes.
   *
   * We recommend at least : `onboarding.read onboarding.write`
   *
   * * `approval_prompt` _string_
   *
   * Can be set to `force` to force showing the consent screen to the merchant, *even when it is not
   * necessary*. If you force an approval prompt and the user creates a new authorization,
   * previously active authorizations will be revoked.
   *
   * Possible values: `auto` `force` (default: `auto`)
   *
   * ### Example of a Complete Redirect URL
   *
   * After adding the above url parameter your URL will look something like this and you can
   * redirect your client to this page:
   *
   * ```
   * https://my.mollie.com/dashboard/client-link/{id}?client_id={your_client_id}&state={unique_state}&scope=onboarding.read%20onboarding.write
   * ```
   *
   * ## Error Handling
   *
   * Error handling is also dealt with similar to the
   * [Authorize](https://docs.mollie.com/reference/authorize) endpoint: the customer is redirected
   * back to your app's redirect URL with the `error` and `error_description` parameters added to
   * the URL.
   *
   * > 🚧 > > A client link must be used within 30 days of creation. After that period, it will
   * expire and you will need to create a new client link.
   *
   * @returns The newly created client link object.
   *
   * @throws {@link ClientLinksApi.CreateClientLinkError} when the API answers with an error status
   * — narrow on `err.payload.kind`
   *
   * @throws {@link MollieApiError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  createClientLink(
    request: ClientLinksApi.CreateClientLinkRequest,
    options?: RequestOptions,
  ): ApiPromise<undefined, ClientLinksApi.CreateClientLinkError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        urlTemplate: this.#servers.default("/v2/client-links"),
        auth: this.#auth.advancedAccessToken,
        pathParams: [],
        query: [],
        headers: [{ name: "idempotency-key", value: request.idempotencyKey, schema: s.optional(s.string()) }],
        body: {
          kind: "json",
          value: request.body,
          schema: s.optional(s.lazy(() => clientLinkRequestSchema)),
        },
      },
      {
        success: { kind: "empty" },
        errorFactory: ClientLinksApi.CreateClientLinkError,
      },
      options,
    );
  }
}

export namespace ClientLinksApi {
  export type CreateClientLinkRequest = {
    /** A unique key to ensure idempotent requests. This key should be a UUID v4 string. */
    idempotencyKey?: string;
    body?: ClientLinkRequest;
  };

  export class CreateClientLinkError extends ApiError {
    declare readonly payload:
      | Declared<"error404", undefined>
      | Declared<"error422", undefined>
      | Declared<"error429", undefined>
      | Undeclared;

    static readonly errors: ErrorDecoders<CreateClientLinkError> = [
      { on: 404, kind: "error404", decode: { kind: "empty" } },
      { on: 422, kind: "error422", decode: { kind: "empty" } },
      { on: 429, kind: "error429", decode: { kind: "empty" } },
    ];
  }
}
